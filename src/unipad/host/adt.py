"""Build the QEMU board's Apple-format device tree (``kernel.macho.adt``).

There are **two different** device trees in this project and they are not
interchangeable:

* the IPSW's own ``DeviceTree`` component -- Apple's description of the real
  iPad7,1 silicon, extracted by :mod:`unipad.host.ipsw` and checked against
  ``board.toml [ipsw.sha256]``.  It is *evidence*: it tells us what the device
  is.  It is never booted.
* ``kernel.macho.adt`` -- a tree that describes the **QEMU virt machine** we
  actually run, generated by the device repository's
  ``scripts/make-qemu-adt.py`` from the device tree QEMU itself dumps, plus the
  board identity.  This is the one XNU reads at boot.

Only the second one is built here.  The distinction is the reason the ADT step
exists as its own stage: a run that "has a device tree" because it extracted
Apple's has no device tree the guest can boot on.

The parameter mapping this module performs is the same one
``scripts/unixnu/payload.py:145-163`` performs for ``unixnu build payload``.
It is written out here rather than shelled out, because the runner's
``step_build_devicetree`` used to pass only ``--output`` and
``--unique-chip-id``: ``--dram-size`` is ``required=True`` in
``make-qemu-adt.py:64``, so that call could only ever fail, and
``--unique-chip-id`` without ``--chip-id`` is refused by :func:`main` at
``make-qemu-adt.py:76-77``.  One mapping, used by both the Windows boot path
and the macOS runner, cannot drift from a third spelling in a shell script.
"""

from __future__ import annotations

import hashlib
import os
