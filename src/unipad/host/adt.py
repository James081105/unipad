#: The board's ``[payload.adt] tool`` relative to the device repository root.
#: ``board.toml`` spells it, so this is only the fallback when a board omits it.
ADT_TOOL = "scripts/make-qemu-adt.py"

#: Domain separator for the platform-seed derivation.  The seed is a *device
#: identity*, not a secret: nothing derives a key from it.  It is kept out of
#: every repository because it identifies one specific checkout's guest, and a
#: value in Git would make every checkout share one identity.  Deriving it from
#: the pinned commit instead of picking a random one keeps the build
#: reproducible while still being unique per pin.
SEED_LABEL = b"unipad/qemu-platform-seed/v1"

#: ``make-qemu-adt.py``'s own default when ``UNIXNU_QEMU_ACCEL`` is unset.  The
#: value decides the device tree's ``timebase-frequency``, and the boot script
#: refuses a tree whose timebase does not match the accelerator it is about to
#: run (``run-qemu.py:120-125``).  Windows QEMU can only emulate AArch64, so
#: this host has exactly one legal value.
TCG_ACCEL = "tcg"

#: The board.toml ``[payload.adt]`` keys and the flag each one becomes, in the
#: order ``payload.py`` emits them.  A key absent from the table is a key the
#: driver does not forward, which is a refusal rather than a silent drop: the
#: board asked for something the caller cannot honour.
ADT_FLAGS: tuple[tuple[str, str], ...] = (
    ("owned_memory_size", "--owned-memory-size"),
    ("root_match_volume_uuid", "--root-match-volume-uuid"),
    ("chip_id", "--chip-id"),
    ("cpu_regs", "--cpu-regs"),
    ("psci_method", "--psci-method"),
)

#: Boolean ``[payload.adt]`` keys that become a bare flag when true.
ADT_SWITCHES: tuple[str, ...] = ("ipad_identity",)


@dataclass(frozen=True)
class BoardAdt:
    """The ``[payload.adt]`` block of the device's board.toml, plus ``dram_size``.

    ``dram_size`` lives in ``[payload]``, not ``[payload.adt]`` -- the driver
    reads it from there (``payload.py:145``) and ``make-qemu-adt.py`` takes it
    as a *required* argument, because it is also the size of the machine whose
    device tree QEMU is asked to dump.  It is carried here so one object
    describes the whole call.

    ``requires_seed`` is ``True`` when ``unique_chip_id`` is the literal string
    ``"required"``, which is how a board says the platform seed must be supplied
    rather than derived from the image.
    """

    tool: str
    chip_id: str
    owned_memory_size: Optional[str]
    root_match_volume_uuid: Optional[str]
    cpu_regs: Optional[str]
    psci_method: Optional[str]
    ipad_identity: bool
    packed_data_ramdisk: bool
    dram_size: int
    requires_seed: bool
    device_dir: Path = field(default=Path("."))
    #: Where the tool is run from.  It is **not** the device repository: the tool
    #: invokes ``scripts/qemu-entry/make-dt.py``, which lives in UniXNU, so the
    #: directory has to be the merged build tree :func:`prepare_tree` assembles.
    #: It defaults to the device repository so a caller that already has such a
    #: tree can point at it directly.
    tree_dir: Path = field(default=Path("."))


def _block(path: Path, name: str) -> dict[str, Any]:
    """Return one table of a board.toml by (possibly dotted) name.

    ``[payload.adt]`` is TOML's spelling for a table nested inside ``[payload]``,
    so ``tomllib`` answers ``board["payload"]["adt"]`` and a literal
    ``board["payload.adt"]`` is always absent.  The name is therefore walked a
    segment at a time -- which is also why a board that genuinely declares no
    ``[payload.adt]`` still has to be refused rather than answered with defaults.
    """
    try:
        board = tomllib.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            f"board.toml not found in {safe_location(path.parent)}",
            path=safe_location(path),
        ) from exc
    except tomllib.TOMLDecodeError as exc:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            f"board.toml is not valid TOML: {safe_location(path)}",
            path=safe_location(path),
            error=str(exc),
        ) from exc
    value: Any = board
    for segment in name.split("."):
        if not isinstance(value, dict) or segment not in value:
            return {}
        value = value[segment]
    if not isinstance(value, dict):
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            f"board.toml [{name}] is not a table",
            path=safe_location(path),
            received_type=type(value).__name__,
        )
    return value


def _int_like(value: Any, key: str, where: Path) -> int:
    """Accept ``0x180000000``, ``"0x180000000"`` and ``6442450944`` alike.

    board.toml spells ``dram_size`` as a TOML *string* containing hex
    (``"0x180000000"``), which ``int(value, 0)`` reads; a bare integer would be
    a different spelling of the same fact and is accepted too rather than
    refused for being written the other way.
    """
    if isinstance(value, bool) or value is None:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            f"board.toml {key} is missing or not a number",
            path=safe_location(where),
            value=repr(value),
        )
    if isinstance(value, int):
        return value
    text = str(value).strip()
    try:
        return int(text, 0)
    except ValueError as exc:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            f"board.toml {key} is not a number",
            path=safe_location(where),
            value=repr(value),
        ) from exc


def read_board_adt(device_dir: Path) -> BoardAdt:
    """Read ``[payload.adt]`` and ``[payload] dram_size`` from a device repo.

    A board with no ``[payload.adt]`` table is refused rather than answered
    with defaults: the QEMU virt board needs a generated tree, and a board that
    declares none would get a tree nobody asked for.
    """
    device_dir = Path(device_dir)
    path = device_dir / "board.toml"
    adt = _block(path, "payload.adt")
    if not adt:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            f"board.toml declares no [payload.adt] table: {safe_location(path)}",
            path=safe_location(path),
        )
    payload = _block(path, "payload")
    if "dram_size" not in payload:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            "board.toml [payload] declares no dram_size, which make-qemu-adt.py "
            "requires and which is also the size of the machine it dumps",
            path=safe_location(path),
        )

    def optional(key: str) -> Optional[str]:
        value = adt.get(key)
        return None if value is None else str(value)

    # ``chip_id`` here is a **hex string without a 0x prefix**: the tool reads it
    # with ``int(value, 16)`` (``make-qemu-adt.py:68``), so ``[payload.adt]
    # chip_id = "207"`` is 0x207 = 519 and not the decimal 207.  Reading it as
    # decimal is the mistake this comment exists to prevent -- it produces a tree
    # whose ``/chosen/chip-id`` disagrees with the board, and the disagreement
    # only surfaces when the tree is read back.
    chip_id = adt.get("chip_id")
    if chip_id is None or not str(chip_id).strip():
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            "board.toml [payload.adt] declares no chip_id; make-qemu-adt.py "
            "refuses --unique-chip-id without --chip-id",
            path=safe_location(path),
        )
    try:
        chip_value = int(str(chip_id).strip(), 16)
    except ValueError as exc:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            "board.toml [payload.adt] chip_id is not a hexadecimal string",
            path=safe_location(path),
            value=repr(chip_id),
        ) from exc
    if not 0 <= chip_value <= 0xFFFFFFFF:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            "board.toml [payload.adt] chip_id does not fit the 4-byte "
            "/chosen/chip-id property the tool writes",
            path=safe_location(path),
            value=chip_value,
        )

    return BoardAdt(
        tool=str(adt.get("tool") or ADT_TOOL),
        chip_id=str(chip_id).strip(),
        owned_memory_size=optional("owned_memory_size"),
        root_match_volume_uuid=optional("root_match_volume_uuid"),
        cpu_regs=optional("cpu_regs"),
        psci_method=optional("psci_method"),
        ipad_identity=bool(adt.get("ipad_identity", False)),
        packed_data_ramdisk=bool(adt.get("packed_data_ramdisk", False)),
        dram_size=_int_like(payload["dram_size"], "[payload] dram_size", path),
        requires_seed=str(adt.get("unique_chip_id", "")).strip().lower() == "required",
        # Absolute, because the tool is run with this directory as its cwd: a
        # relative device dir would make the tool's own path resolve twice
        # against it and point at a repository that does not exist.
        device_dir=device_dir.resolve(),
        tree_dir=device_dir.resolve(),
    )


def prepare_tree(unixnu_dir: Path, device_dir: Path, tree_dir: Path) -> Path:
    """Assemble the ``scripts/`` directory the ADT tool needs, and return the tree.

    ``make-qemu-adt.py`` lives in the *device* repository but invokes
    ``scripts/qemu-entry/make-dt.py``, which lives in *UniXNU*
    (``make-qemu-adt.py:82``).  Neither repository alone can run it.  Upstream
    resolves this by assembling ``out/<device>/tree/`` with ``scripts/`` copied
    from both repositories (``unixnu/tree.py:assemble``), the device copied
    **last** so a device's spelling of a script wins.

    This is that copy step, and only that step: the ADT tool needs no modules,
    no feeds and no package, so a full tree assembly would be a long way round
    to two files.  The device repository is copied second for the same reason
    upstream copies it second.

    Args:
        unixnu_dir: The UniXNU repository root (``vendor/UniXNU``).
        device_dir: The device repository root (``vendor/UniXNU-qemu``).
        tree_dir: Where to build.  Recreated, so a stale script cannot survive
            a pin change.

    Returns:
        ``tree_dir``, resolved.
    """
    tree = Path(tree_dir).resolve()
    scripts = tree / "scripts"
    if scripts.is_dir():
        shutil.rmtree(scripts)
    scripts.mkdir(parents=True)

    copied = 0
    for base in (Path(unixnu_dir), Path(device_dir)):
        source = Path(base) / "scripts"
        if not source.is_dir():
            continue
        for path in sorted(source.rglob("*")):
            relative = path.relative_to(source)
            # tree.py:_copy_scripts skips the driver package itself (the scripts
            # locate the tree from their own real path, so a copy of the driver
            # inside the tree would shadow it) and any bytecode cache.
            if path.is_dir() or "__pycache__" in path.parts or relative.parts[0] == "unixnu":
                continue
            target = scripts / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
            copied += 1

    tool = tree / ADT_TOOL
    if not tool.is_file():
        raise UniPadError(
            ErrorCode.ARTIFACT_MISSING,
            f"the merged tree has no {ADT_TOOL}: neither repository supplied it",
            unixnu=safe_location(unixnu_dir),
            device=safe_location(device_dir),
            tree=safe_location(tree),
        )
    make_dt = scripts / "qemu-entry" / "make-dt.py"
    if not make_dt.is_file():
        raise UniPadError(
            ErrorCode.ARTIFACT_MISSING,
            "the merged tree has no scripts/qemu-entry/make-dt.py, which "
            "make-qemu-adt.py:82 invokes and which only UniXNU carries",
            unixnu=safe_location(unixnu_dir),
            tree=safe_location(tree),
        )
    return tree


def derive_seed(head: str) -> bytes:
    """Derive the 64-bit platform seed from the device repository's pinned commit.

    The seed is a per-checkout device identity that lives outside both
    repositories (``README.md:71`` of UniXNU-qemu: "created once per checkout and
    stays out of Git").  Nothing upstream generates one, so a caller has to.

    Deriving it from the pinned commit rather than drawing a random value keeps
    the whole build reproducible: the same pin gives the same guest identity, and
    a different pin gives a different one.  Any 64-bit value is accepted by the
    consumer (``make-qemu-adt.py:67`` does ``int(value, 16)`` and
    ``struct.pack('<Q', ...)``), so there is nothing to get wrong about the value
    itself -- only about it being stable.

    Args:
        head: The full commit id of the device repository checkout.

    Returns:
        Eight bytes, the first 8 of ``SHA-256(SEED_LABEL || 0x00 || ascii(head))``.
    """
    digest = hashlib.sha256(SEED_LABEL + b"\0" + head.encode("ascii")).digest()
    return digest[:8]


def adt_command(
    board: BoardAdt,
    output: Path,
    *,
    seed: Optional[str] = None,
    data_ramdisk: bool = False,
    trust_cache: bool = False,
) -> list[str]:
    """Build the ``make-qemu-adt.py`` argv for ``board``.

    This is the one place the board.toml-to-flag mapping lives.  It mirrors
    ``scripts/unixnu/payload.py:145-163`` exactly, including the two conditions
    that are easy to get wrong:

    * ``--dram-size`` is emitted unconditionally, from ``[payload] dram_size``.
    * ``--unique-chip-id`` and ``--chip-id`` travel together, because
      ``make-qemu-adt.py:76-77`` refuses one without the other.
    * ``--packed-data-ramdisk`` / ``--data-ramdisk`` are only emitted when a data
      ramdisk is actually being supplied; the board's
      ``packed_data_ramdisk = true`` says *which* of the two, not *whether*.

    Raises:
        UniPadError: ``config_invalid`` when the board requires a platform seed
            and none was given.
    """
    if board.requires_seed and not seed:
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            "the platform seed is not stored in any repository: pass --unique-chip-id HEX "
            "(board.toml [payload.adt] unique_chip_id = \"required\")",
            device_dir=safe_location(board.device_dir),
        )

    command = ["python3", board.tree_dir / board.tool, "--output", Path(output)]
    command += ["--dram-size", str(board.dram_size)]
    for key, flag in ADT_FLAGS:
        value = getattr(board, key, None)
        if value is not None:
            command += [flag, str(value)]
    if seed:
        command += ["--unique-chip-id", seed]
    if data_ramdisk:
        command.append("--packed-data-ramdisk" if board.packed_data_ramdisk else "--data-ramdisk")
    if trust_cache:
        command.append("--trust-cache")
    for switch in ADT_SWITCHES:
        if getattr(board, switch, False):
            command.append("--" + switch.replace("_", "-"))
    return [str(part) for part in command]


