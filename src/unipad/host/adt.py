def parse_adt(blob: bytes) -> tuple[list, int]:
    """Parse an Apple device tree into ``(node, end_offset)``.

    The format is the one ``make-qemu-adt.py:22-37`` reads and writes: a node is
    a property count and a child count, then that many ``[32-byte key][u32
    length][padded value]`` triples, then that many children.  The parser is a
    transcription of the tool's own so a tree this module produces can be read
    back by the same rules the tool used to write it.
    """
    return _parse(blob, 0)


def _parse(blob: bytes, at: int) -> tuple[list, int]:
    if at + 8 > len(blob):
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            "the device tree is truncated before its node header",
            offset=at,
            size=len(blob),
        )
    count, children = struct.unpack_from("<II", blob, at)
    at += 8
    properties: list[tuple[str, bytes]] = []
    for _ in range(count):
        if at + 36 > len(blob):
            raise UniPadError(
                ErrorCode.VERIFICATION_FAILED,
                "the device tree is truncated inside a property header",
                offset=at,
                size=len(blob),
            )
        key = blob[at : at + 32].split(b"\0")[0].decode("ascii", "replace")
        (length,) = struct.unpack_from("<I", blob, at + 32)
        at += 36
        if at + length > len(blob):
            raise UniPadError(
                ErrorCode.VERIFICATION_FAILED,
                "the device tree is truncated inside a property value",
                key=key,
                offset=at,
                size=len(blob),
            )
        properties.append((key, blob[at : at + length]))
        at += length + (-length % 4)
    kids: list[list] = []
    for _ in range(children):
        child, at = _parse(blob, at)
        kids.append(child)
    names = [name for name, _, _ in kids]
    return [dict(properties).get("name", b"").rstrip(b"\0").decode("ascii", "replace"), properties, kids], at


def find_node(root: list, name: str) -> Optional[list]:
    """Depth-first search for the first node named ``name``."""
    stack = [root]
    while stack:
        node = stack.pop()
        if node[0] == name:
            return node
        stack.extend(reversed(node[2]))
    return None


def node_property(node: Optional[list], key: str) -> Optional[bytes]:
    """The value of ``key`` on ``node``, or ``None`` when the node lacks it."""
    if node is None:
        return None
    for existing, value in node[1]:
        if existing == key:
            return value
    return None


def verify_adt(path: Path, board: BoardAdt, seed: Optional[str] = None) -> dict[str, Any]:
    """Check a generated tree carries the identity the board asked for.

    This is the load-bearing check.  A tree that parses but carries no
    ``unique-chip-id`` boots a guest with no platform identity, and
    ``IOPlatformExpertDevice::generatePlatformUUID`` then leaves
    ``IOPlatformUUID`` empty -- which surfaces much later as userland that
    cannot start, not as a boot failure.  So the properties are checked here,
    where the failure can name them.

    Returns:
        A record of what was found, for the evidence bundle.

    Raises:
        UniPadError: ``artifact_invalid`` for anything the board asked for and
            the tree does not carry.
    """
    blob = Path(path).read_bytes()
    root, end = parse_adt(blob)
    if end != len(blob):
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            "the device tree has trailing bytes after the root node",
            path=safe_location(path),
            parsed=end,
            size=len(blob),
        )

    chosen = find_node(root, "chosen")
    if chosen is None:
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            "the device tree has no /chosen node",
            path=safe_location(path),
        )
    defaults = find_node(root, "defaults")
    arm_io = find_node(root, "arm-io")

    record: dict[str, Any] = {
        "path": safe_location(path),
        "bytes": len(blob),
        "sha256": hashlib.sha256(blob).hexdigest(),
        "model": (node_property(root, "model") or b"").rstrip(b"\0").decode("ascii", "replace"),
        "target_type": (node_property(root, "target-type") or b"").rstrip(b"\0").decode("ascii", "replace"),
        "sleep_disabled": node_property(defaults, "sleep-disabled") == struct.pack("<I", 1),
        "maxvnodes": struct.unpack("<I", node_property(defaults, "kern.maxvnodes") or b"")[0]
        if node_property(defaults, "kern.maxvnodes")
        else None,
    }

    chip_id = node_property(chosen, "chip-id")
    if chip_id is None or len(chip_id) != 4:
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            "the device tree carries no 4-byte /chosen/chip-id",
            path=safe_location(path),
            found=None if chip_id is None else len(chip_id),
            expected=int(board.chip_id, 16),
        )
    record["chip_id"] = struct.unpack("<I", chip_id)[0]
    if record["chip_id"] != int(board.chip_id, 16):
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            "/chosen/chip-id does not match board.toml [payload.adt] chip_id",
            path=safe_location(path),
            found=record["chip_id"],
            expected=int(board.chip_id, 16),
        )

    if seed:
        unique = node_property(chosen, "unique-chip-id")
        if unique is None or len(unique) != 8:
            raise UniPadError(
                ErrorCode.VERIFICATION_FAILED,
                "the device tree carries no 8-byte /chosen/unique-chip-id",
                path=safe_location(path),
                found=None if unique is None else len(unique),
            )
        record["unique_chip_id"] = struct.unpack("<Q", unique)[0]
        if f"{record['unique_chip_id']:x}" != seed.strip().lower().removeprefix("0x"):
            raise UniPadError(
                ErrorCode.VERIFICATION_FAILED,
                "/chosen/unique-chip-id is not the platform seed that was passed",
                path=safe_location(path),
                found=f"{record['unique_chip_id']:x}",
                expected=seed,
            )

    if board.root_match_volume_uuid:
        matching = node_property(chosen, "root-matching")
        record["root_matching"] = (matching or b"").decode("ascii", "replace")

    if board.ipad_identity:
        if record["model"] != "iPad7,1":
            raise UniPadError(
                ErrorCode.VERIFICATION_FAILED,
                "the device tree does not carry the iPad identity board.toml asked for",
                path=safe_location(path),
                model=record["model"],
                expected="iPad7,1",
            )
        record["product_name"] = (
            node_property(find_node(root, "product"), "product-name") or b""
        ).rstrip(b"\0").decode("ascii", "replace")

    # make-qemu-adt.py:127 removes QEMU's UFS nodes, which the guest has no
    # controller for.  Their presence is a sign the tree was not the one this
    # board's tool produced.
    if arm_io is not None:
        leftover = sorted(child[0] for child in arm_io[2] if child[0] in ("ufshc", "ufsphy"))
        if leftover:
            raise UniPadError(
                ErrorCode.VERIFICATION_FAILED,
                "the device tree still carries QEMU's UFS nodes, which this board "
                "removes because the guest has no UFS controller",
                path=safe_location(path),
                nodes=leftover,
            )

    record["timebase_hz"] = (
        struct.unpack("<I", node_property(find_node(root, "cpu0"), "timebase-frequency") or b"")[0]
        if node_property(find_node(root, "cpu0"), "timebase-frequency")
        else None
    )
    return record


