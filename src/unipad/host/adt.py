def _tool_environment(qemu: Path, accel: str = TCG_ACCEL) -> dict[str, str]:
    """The environment ``make-qemu-adt.py`` needs to run on Windows.

    The tool shells out twice by bare name: ``shutil.which('qemu-system-aarch64')``
    at ``make-qemu-adt.py:93-95`` and ``['python3', .../make-dt.py, ...]`` at
    ``:82``.  On Windows neither name exists unless a directory carrying it is on
    ``PATH``, so the caller's QEMU directory and a ``python3`` shim directory are
    prepended for the child only -- the host's own environment is not modified.

    ``UNIXNU_QEMU_ACCEL`` is forwarded because the tool reads it for the
    timebase, and a tree built for one accelerator is refused by the boot script
    running another (``run-qemu.py:120-125``).
    """
    env = dict(os.environ)
    qemu = Path(qemu).resolve()
    if not qemu.is_file():
        raise UniPadError(
            ErrorCode.CONFIG_INVALID,
            "qemu-system-aarch64 not found; make-qemu-adt.py dumps the machine's "
            "device tree through it and cannot run without it",
            path=safe_location(qemu),
        )
    directories = [str(qemu.parent)]
    for shim in _python3_shims():
        directories.append(str(shim))
    env["PATH"] = os.pathsep.join(directories + [env.get("PATH", "")])
    env["UNIXNU_QEMU_ACCEL"] = accel
    return env


def _python3_shims() -> list[Path]:
    """Directories that carry a ``python3`` executable, most likely first."""
    candidates: list[Path] = []
    for name in ("python3", "python3.exe", "python3.cmd"):
        found = shutil.which(name)
        if found:
            candidates.append(Path(found).resolve().parent)
    # A shim shipped with the toolchain: the host account may have no python3 at
    # all (Windows names it python.exe), while the upstream scripts all invoke
    # python3 by name.
    for shim in (
        Path(__file__).resolve().parents[2] / "local-private" / "tools" / "bin",
        Path(__file__).resolve().parents[3] / "local-private" / "tools" / "bin",
    ):
        if (shim / "python3.exe").is_file() or (shim / "python3").is_file():
            candidates.append(shim)
    unique: list[Path] = []
    for candidate in candidates:
        if candidate not in unique:
            unique.append(candidate)
    return unique


def generate(
    board: BoardAdt,
    output: Path,
    *,
    qemu: Path,
    seed: Optional[str] = None,
    accel: str = TCG_ACCEL,
    data_ramdisk: bool = False,
    trust_cache: bool = False,
    log_path: Optional[Path] = None,
    timeout: float = 300.0,
) -> dict[str, Any]:
    """Run the board's ADT tool and verify what it wrote.

    The tool is run with :func:`_tool_environment`, so the caller's ``PATH`` is
    untouched and the child sees exactly the two executables it needs.

    Returns:
        The :func:`verify_adt` record, which is also the evidence: it names the
        tree's bytes, its sha256, the identity properties it carries and the
        timebase the accelerator requires.

    Raises:
        UniPadError: ``artifact_invalid`` when the tool fails, writes a tree
            that does not parse, or writes one that does not carry the identity
            the board asked for.
    """
    output = Path(output).resolve()
    command = adt_command(board, output, seed=seed, data_ramdisk=data_ramdisk, trust_cache=trust_cache)
    env = _tool_environment(qemu, accel)
    # ``CreateProcess`` resolves the executable against the *parent's* PATH, not
    # the one handed over in ``env``, so ``["python3", ...]`` raises
    # ``FileNotFoundError`` even though the child's PATH would find it.  The head
    # of the argv is therefore resolved here, against the augmented PATH this
    # module just built, and replaced with the absolute path.  Upstream spells
    # the bare name because on macOS that is how ``PATH`` works.
    command = list(command)
    interpreter = shutil.which(command[0], path=env.get("PATH", os.environ.get("PATH", "")))
    if interpreter is None:
        raise UniPadError(
            ErrorCode.BLOCKED,
            f"{command[0]} not found: make-qemu-adt.py invokes make-dt.py by that "
            "name and Windows spells it python.exe",
            searched=env.get("PATH", "").split(os.pathsep),
        )
    command[0] = interpreter

    if log_path is not None:
        log_path = Path(log_path)
        log_path.parent.mkdir(parents=True, exist_ok=True)
        handle = log_path.open("w", encoding="utf-8", errors="replace")
    else:
        handle = None
    try:
        completed = subprocess.run(
            command,
            cwd=str(board.tree_dir),
            env=env,
            stdout=handle if handle is not None else subprocess.PIPE,
            stderr=subprocess.STDOUT if handle is not None else subprocess.PIPE,
            timeout=timeout,
            text=handle is None,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            f"the device tree tool did not finish within {timeout:.0f}s",
            command=command,
            tool=board.tool,
        ) from exc
    except OSError as exc:
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            "the device tree tool could not be started",
            command=command,
            reason=type(exc).__name__,
        ) from exc
    finally:
        if handle is not None:
            handle.close()

    if completed.returncode != 0:
        detail = "" if handle is not None else (completed.stdout or "")
        raise UniPadError(
            ErrorCode.VERIFICATION_FAILED,
            f"{board.tool} failed with exit code {completed.returncode}",
            command=command,
            output=detail[-4000:],
        )
    if not output.is_file():
        raise UniPadError(
            ErrorCode.ARTIFACT_MISSING,
            f"{board.tool} reported success but wrote no device tree",
            path=safe_location(output),
        )
    return verify_adt(output, board, seed=seed)


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Command line: ``python -m unipad.host.adt --device DIR --qemu QEMU --out FILE``."""
    import argparse

    from unipad.host.ipsw import sha256_file

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--device", type=Path, required=True, help="device repository root (holds board.toml)")
    parser.add_argument("--qemu", type=Path, required=True, help="qemu-system-aarch64 executable")
    parser.add_argument("--out", type=Path, required=True, help="where to write kernel.macho.adt")
    parser.add_argument("--unixnu", type=Path, default=None,
                        help="UniXNU repository root; needed because make-qemu-adt.py invokes "
                             "scripts/qemu-entry/make-dt.py, which only UniXNU carries")
    parser.add_argument("--tree", type=Path, default=None,
                        help="an already-assembled build tree to run the tool from; with --unixnu "
                             "it is built instead, at the same path")
    parser.add_argument("--seed", default=None, help="platform seed as hex; required when board.toml says so")
    parser.add_argument("--derive-seed-from", default=None, metavar="COMMIT",
                        help="derive the seed from this commit instead of passing --seed")
    parser.add_argument("--accel", default=TCG_ACCEL, choices=("tcg",), help="guest accelerator")
    parser.add_argument("--data-ramdisk", action="store_true",
                        help="emit /chosen/memory-map/PackedRAMDisk, the zeroed 16-byte "
                             "placeholder DarwinBoot patches with the packed Data ramdisk's "
                             "address and size.  Required by, and only useful with, a boot "
                             "that carries a data ramdisk (unipad.host.unixnu_boot "
                             "--data-ramdisk): DarwinBoot accepts both or neither")
    parser.add_argument("--log", type=Path, default=None, help="write the tool's output here")
    args = parser.parse_args(argv)

    seed = args.seed
    if seed is None and args.derive_seed_from:
        seed = derive_seed(args.derive_seed_from).hex()

    board = read_board_adt(args.device)
    tree_dir = board.tree_dir
    if args.unixnu is not None:
        tree_dir = prepare_tree(args.unixnu, args.device, args.tree or (args.device.parent / "tree"))
        board = replace(board, tree_dir=tree_dir)
    elif args.tree is not None:
        board = replace(board, tree_dir=Path(args.tree).resolve())

    record = generate(
        board,
        args.out,
        qemu=args.qemu,
        seed=seed,
        accel=args.accel,
        data_ramdisk=args.data_ramdisk,
        log_path=args.log,
    )
    print(f"device tree: {record['bytes']} bytes, sha256 {record['sha256']}")
    print(f"  model {record['model']!r} target-type {record['target_type']!r} chip-id {record.get('chip_id')}")
    if "unique_chip_id" in record:
        print(f"  unique-chip-id {record['unique_chip_id']:x} timebase {record.get('timebase_hz')} Hz")
    print(f"  packed-data-ramdisk: {bool(args.data_ramdisk)}")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    raise SystemExit(main())
