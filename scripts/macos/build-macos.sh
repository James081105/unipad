# ---------------------------------------------------------------------------
# this repository's own Python package
# ---------------------------------------------------------------------------
# run_unipad ARGS... -- run this repository's unipad package with the
# interpreter this script already resolved.
#
# The package lives in src/ and is NOT installed on a GitHub runner: there is no
# editable shim there, and `python3 -m unipad.host.ipsw` died with
# ModuleNotFoundError: No module named 'unipad' until the workflow set
# PYTHONPATH=src (measured on run 40065266844).  So the path is supplied here
# rather than assumed, and it is supplied inside a subshell so no other step's
# child -- the upstream driver above all, which puts its own scripts/ on
# sys.path -- inherits a sys.path it did not have.
run_unipad() {
    ( export PYTHONPATH="$REPO_ROOT/src${PYTHONPATH:+:$PYTHONPATH}"; "$PY" "$@" )
}

# ---------------------------------------------------------------------------
# the platform seed
# ---------------------------------------------------------------------------
# unipad.host.adt owns the whole board.toml [payload.adt] -> flag mapping and
# the derivation (adt.py:343-364).  What is left to the shell is the one input
# that is in no repository: the platform seed.
#
# It is a device identity, not a secret -- nothing derives a key from it
# (adt.py:62-68) -- but it is deliberately in no Git: a value committed anywhere
# would give every checkout of the same pin the same guest identity, which is
# the one thing the seed exists to distinguish.  A run that was not given one
# therefore derives it from the pinned device commit and keeps the result in its
# own workspace.  Deterministic, so the same pin reproduces the same guest; per
# pin, so two pins are two guests.
platform_seed_path() { printf '%s' "$OUT_DIR/platform-seed"; }

# derive_platform_seed -- print the 16-hex seed for the pinned device commit.
#
# The pin comes from the lock file, which is the authority (PRD 8.1); the
# checkout's own HEAD is the fallback, for a run whose lock was overridden.
# Fails, printing nothing, when neither is a commit.
derive_platform_seed() {
    local head="$LOCK_DEVICE_COMMIT"
    [[ -n "$head" ]] || head="$(head_of "$DEVICE_DIR")"
    [[ "$head" =~ ^[0-9a-fA-F]{7,64}$ ]] || return 1
    run_unipad - "$head" <<'PY'
import sys

from unipad.host.adt import derive_seed

print(derive_seed(sys.argv[1]).hex())
PY
}

# persist_platform_seed SEED ORIGIN COMMIT -- write the seed and its provenance
# into the run's workspace, and record the seed's sha256 so the ledger can name
# it without printing the value into a file that gets uploaded.
persist_platform_seed() {
    local seed="$1" origin="$2" commit="$3" digest
    digest="$(printf '%s' "$seed" | "${SHA_CMD[@]}" | awk '{print $1}' | tr 'A-F' 'a-f')"
    printf '%s\n' "$seed" >"$(platform_seed_path)"
    chmod 600 -- "$(platform_seed_path)" 2>/dev/null || true
    PLATFORM_SEED_SHA256="$digest"
    {
        printf '{\n'
        printf '  "seed_sha256": "%s",\n' "$(json_escape "$digest")"
        printf '  "origin": "%s",\n'      "$(json_escape "$origin")"
        printf '  "device_repo_commit": "%s"\n' "$(json_escape "$commit")"
        printf '}\n'
    } >"$OUT_DIR/platform-seed.json"
    assert_json_file "$OUT_DIR/platform-seed.json" 'platform seed record' 'evidence_incomplete'
}

# adt_qemu_path -- where qemu-system-aarch64 is, or nothing.
#
# PATH first, then the two Homebrew prefixes by hand: `brew install` puts the
# binary in a directory a freshly-started shell may not have on PATH (the runner
# adds it to $GITHUB_PATH for *later* steps), so a post-install lookup that only
# consults PATH would report "installed but absent" and record the sub-step
# not_run for a reason that is not the real one.
#
# A candidate is only returned when it is a file, because what comes back is
# handed to the module as --qemu and the module refuses a path that is not one
# (adt.py:638-645).  Returning something that is not there would trade a clear
# refusal here for a traceback one layer down.
adt_qemu_path() {
    local found dir
    found="$(command -v qemu-system-aarch64 2>/dev/null || true)"
    if [[ -n "$found" && -f "$found" ]]; then
        printf '%s' "$found"
        return 0
    fi
    for dir in "${HOMEBREW_PREFIXES[@]}"; do
        for found in "$dir/qemu-system-aarch64" "$dir/qemu-system-aarch64.exe"; do
            if [[ -f "$found" ]]; then
                printf '%s' "$found"
                return 0
            fi
        done
    done
    return 0
}

# ensure_qemu NAME -- make qemu-system-aarch64 available for NAME's step, and
# record the step's own ledger entry when it cannot be.
#
# Returns 0 when QEMU is there (or was just installed), 1 when brew was tried and
# failed, and 2 when there is no brew to try with.  The ledger entry is written
# HERE rather than by the caller, so the two consumers cannot drift about what an
# absent QEMU means:
#
#   * absent and no package manager -> not_run.  An environment blocker, not a
#     failure of the build; the run's verdict stays honest without the plan
#     stopping.  This is the Windows / bare-runner case.
#   * brew ran and failed -> failed, with the brew output in the step's log.  The
#     runner was supposed to be able to install it and could not, which is this
#     step's own failure.
#   * brew reported success but the binary is nowhere -> not_run, naming the
#     prefixes that were searched, because "it installed but I cannot find it" is
#     not a build failure either.
#
# This is the ADT-only spelling of payload_tools_ready, which asks for mtools as
# well because build-payload writes its volume with mformat/mcopy
# (payload.py:56-58).  The device tree needs one package, so one package is asked
# for -- see "Eliminate Effects Between Unrelated Things".
ensure_qemu() {
    local name="$1" log_file="$OUT_DIR/${name//\//-}.brew.log" where
    where="$(adt_qemu_path)"
    if [[ -n "$where" ]]; then
        return 0
    fi
    if ! command -v brew >/dev/null 2>&1; then
        ledger_add "$name" 'not_run' \
            'make-qemu-adt.py dumps the device tree of the machine it describes through qemu-system-aarch64 (make-qemu-adt.py:93-101) and refuses without it (make-qemu-adt.py:95, "brew install qemu"); it is absent and there is no brew on this runner to install it with'
        return 2
    fi
    log "adt: qemu-system-aarch64 is absent; installing it (brew install qemu)"
    if ! brew install qemu >"$log_file" 2>&1; then
        printf 'brew install qemu failed; its output is in %s and its tail follows:\n' \
            "$(shown_path "$log_file")" >&2
        tail -n 20 "$log_file" >&2 || true
        ledger_add "$name" 'failed' \
            "brew install qemu failed; see $(shown_path "$log_file"). make-qemu-adt.py:93-101 dumps the machine's device tree through qemu-system-aarch64 and cannot run without it"
        return 1
    fi
    where="$(adt_qemu_path)"
    if [[ -z "$where" ]]; then
        ledger_add "$name" 'not_run' \
            'make-qemu-adt.py dumps the device tree of the machine it describes through qemu-system-aarch64 (make-qemu-adt.py:93-101); brew install qemu reported success but the binary is neither on PATH nor in /opt/homebrew/bin or /usr/local/bin'
        return 2
    fi
    TOOL_QEMU="$where"
    log "adt: qemu installed at $TOOL_QEMU (log: $(shown_path "$log_file"))"
    return 0
}

# lock_entries -- 'submodule<TAB>path<TAB>commit' and 'feed<TAB>name<TAB>commit'
# for every source the lock file pins.  The lock, not the repositories, is the
# authority (PRD 8.1).
lock_entries() {
    "$PY" - "$LOCK_PATH" <<'PY'
import json
import sys

with open(sys.argv[1], 'r', encoding='utf-8') as handle:
    root = json.load(handle)
for entry in root.get('submodules') or []:
    print('submodule\t%s\t%s' % (entry.get('path') or '', entry.get('commit') or ''))
for entry in root.get('feeds') or []:
    print('feed\t%s\t%s' % (entry.get('name') or '', entry.get('commit') or ''))
PY
}

# offline_missing -- 'kind<TAB>name' for every pinned source the driver would
# have to fetch.  prepare() fetches any git feed whose clone is absent or at the
# wrong commit (cli.py:79-86, feeds.py:173-216) and initialises module
# submodules (feeds.py:159-165); both reach the network, so this script proves
# they are already on disk at the pinned commit before it runs anything.
# Measured on this host: without this guard `unixnu build kernel` reaches
# `git fetch https://github.com/apple-oss-distributions/xnu.git` and fails.
offline_missing() {
    local kind name commit dir found
    while IFS="$(printf '\t')" read -r kind name commit; do
        # A Windows interpreter writes CRLF on a pipe, so the last field of
        # every line arrives with a trailing \r.  validate_lock() strips it for
        # the same reason (see the comment there); without the strip here the
        # pinned commit never equals the one git reports and EVERY source reads
        # as absent -- measured: a feed clone sitting on disk at exactly the
        # locked commit was still reported as "the driver would have to fetch".
        name="${name%$'\r'}"
        commit="${commit%$'\r'}"
        [[ -n "$commit" ]] || continue
        found=0
        case "$kind" in
            submodule)
                for dir in "$UNIXNU_DIR/$name" "$DEVICE_DIR/$name"; do
                    if [[ -d "$dir" && "$(head_of "$dir")" == "$commit" ]]; then
                        found=1
                        break
                    fi
                done
                ;;
            feed)
                for dir in "$FEEDS_DIR"/*; do
                    if [[ -d "$dir" && "$(head_of "$dir")" == "$commit" ]]; then
                        found=1
                        break
                    fi
                done
                ;;
        esac
        if (( found == 0 )); then
            printf '%s\t%s\n' "$kind" "$name"
        fi
    done < <(lock_entries)
}

# apple_step_gate NAME REQUIREMENT...
# Returns 0 when the stage may run.  Otherwise records NAME as not_run with
# every reason found at once -- the host and the missing tools together, so the
# ledger never has to be read twice to learn why a stage did not run -- and
# returns 1.  A requirement that looks like a path is checked as a directory
# (the Homebrew LLVM keg), anything else with command -v.
apple_step_gate() {
    local name="$1"; shift
    local host requirement reason
    host="$(uname -s 2>/dev/null || printf '%s' 'unknown')"
    local -a missing=()
    for requirement in "$@"; do
        case "$requirement" in
            /*) if [[ ! -d "$requirement" ]]; then missing+=("$requirement"); fi ;;
            *)  if ! command -v "$requirement" >/dev/null 2>&1; then
                    missing+=("$requirement")
                fi ;;
        esac
    done
    if [[ "$host" == 'Darwin' ]] && (( ${#missing[@]} == 0 )); then
        return 0
    fi
    reason=''
    if [[ "$host" != 'Darwin' ]]; then
        reason="host is $host and the Apple toolchain exists on macOS only (PRD 8.1)"
    fi
    if (( ${#missing[@]} > 0 )); then
        if [[ -n "$reason" ]]; then reason+='; '; fi
        reason+="missing: ${missing[*]}"
    fi
    ledger_add "$name" 'not_run' "$reason"
    return 1
}

# log_keg -- report which Homebrew LLVM keg, if any, is on disk.
# Informational only.  See the HOMEBREW_LLVM_DIRS comment: util.tool() finds keg
# tools without the keg being on PATH, so an absent keg is something the driver
# reports precisely ("llvm-lib not found on PATH (brew install llvm lld)"), not
# something this script refuses up front.
log_keg() {
    local keg found=''
    for keg in "${HOMEBREW_LLVM_DIRS[@]}"; do
        if [[ -d "$keg" ]]; then found="$keg"; break; fi
    done
    if [[ -n "$found" ]]; then
        log "llvm keg: $found (util.tool() also finds keg-only tools when it is not on PATH)"
    else
        log "llvm keg: none of ${HOMEBREW_LLVM_DIRS[*]} on disk; the driver looks there and names what it cannot find"
    fi
}

# run_driver STEP SUBCOMMAND ARGS...
# Echoes the command, runs it with its output in OUT_DIR/<step>.driver.log, and
# returns the driver's exit status.  A nonzero status is a stage failure and is
# recorded as one; it is never folded into "ran".
run_driver() {
    local step="$1"; shift
    local sub="$1"; shift
    local -a cmd=("$PY" "$DRIVER" "$sub" -D "$DEVICE_DIR" --out "$UNIXNU_OUT" -j "$JOBS" "$@")
    local log_file="$OUT_DIR/${step}.driver.log"
    log "+ ${cmd[*]}"
    local status=0
    "${cmd[@]}" 2>&1 | tee "$log_file" || status=$?
    # ...and put the module submodules back where the lock pins them.
    #
    # Every driver subcommand that reaches prepare() runs
    # `git submodule update --init --recursive` (cli.py:79-86 ->
    # feeds.py:159-165), which resets EVERY module submodule to the commit the
    # DRIVER's gitlink records -- including the ones sources.lock.json
    # deliberately pins elsewhere.  Measured on runs 40209085545 and
    # 40217489782: the owner root chain built the Legacy display archive at the
    # locked eb9c949, `unixnu build kernel` reset the checkout to the gitlink's
    # c031d882, and build-xnu-4k-baseline.sh:735 refused to link with
    # "Rebuild the owned Legacy archive after changing
    # drivers/NativeMobileDisplay/NativeLegacyDisplay.cpp" -- nine steps from
    # anything that looked like a submodule problem.
    #
    # The half that actually fixes it is inside the module: `pin` also sets
    # submodule.<path>.update=none, which is read by the very command doing the
    # reset ("Skipping submodule ..."), so the reset stops happening at all.
    #
    # This call is the belt to that braces -- measured on run 40217489782, a
    # repair here ran at 17:50:36.310, one second AFTER the link script had
    # refused at 17:50:35.288, because the reset is the driver's FIRST act and
    # everything it builds afterwards sees the gitlink's commit.  It stays
    # because it is idempotent (a rev-parse per pinned submodule, a fetch only
    # for one that really moved) and because it is what would notice a future
    # driver that ignores the setting.
    #
    # It is applied HERE, after every driver call whatever the subcommand,
    # rather than remembered by each caller: a caller that forgets is the same
    # defect one level up.  A pin that cannot be applied is a refusal, not a
    # warning: the build would otherwise not be the pinned one.
    pin_module_submodules "$step"
    return "$status"
}

# pin_module_submodules STEP -- put every module submodule of the driver
# repository at the commit config/sources.lock.json pins.
#
# The logic lives in unipad.host.source_pins, not here, because the workflow's
# acquisition step applies the same pins before `unixnu fetch` initialises the
# submodules from the gitlink -- and two implementations of "which commit" is
# the second-place-that-knows-a-sha defect this project keeps hitting (PRD 8.1).
pin_module_submodules() {
    local step="$1"
    local log_file="$OUT_DIR/${step}.pins.log"
    if run_unipad -m unipad.host.source_pins \
            --lock "$LOCK_PATH" --driver "$UNIXNU_DIR" --quiet \
            >"$log_file" 2>&1; then
        # --quiet prints nothing when nothing moved, so a non-empty log IS the
        # "something moved" signal and there is no second thing to parse.
        if [[ -s "$log_file" ]]; then
            sed 's/^/pins: /' "$log_file"
        fi
        return 0
    fi
    sed 's/^/pins: /' "$log_file" >&2 || true
    die 'verification_failed' \
        'the module submodules could not be put at the commits sources.lock.json pins, so this build would not be the pinned one' \
        "{\"log\":\"$(json_escape "$log_file")\",\"lock\":\"$(json_escape "$LOCK_PATH")\",\"driver\":\"$(json_escape "$UNIXNU_DIR")\"}" \
        "$EXIT_FAILURE"
}

# shown_path PATH -- how the manifest records PATH.
# A path inside this run's output directory is recorded relative to it, so the
# manifest is portable; anything else keeps the path it was given.  One helper,
# used by both the built artifacts and the declared ones, so the two cannot
# disagree about what a path means.
shown_path() {
    local path="$1"
    case "$path" in
        "$OUT_DIR"/*) printf '%s' "${path#"$OUT_DIR"/}" ;;
        *)            printf '%s' "$path" ;;
    esac
}

# record_artifact PATH ROLE [ARCH]
# One manifest record for a file a stage actually produced.  A stage that
# produced nothing records nothing: the manifest never carries a hash of a file
# that is not there.
record_artifact() {
    local path="$1" role="$2" arch="${3:-aarch64}" sha size leaf
    if [[ ! -f "$path" ]]; then
        die 'evidence_incomplete' \
            "a stage reported $path but the file does not exist." \
            "{\"path\":\"$(json_escape "$path")\"}" "$EXIT_FAILURE"
    fi
    sha="$(sha256_of "$path")"
    if [[ ! "$sha" =~ $SHA256_PATTERN ]]; then
        die 'verification_failed' "could not compute the SHA-256 of $path." \
            "{\"path\":\"$(json_escape "$path")\"}" "$EXIT_FAILURE"
    fi
    size="$(wc -c <"$path" | tr -d ' ')"
    leaf="$(basename -- "$path")"
    local shown
    shown="$(shown_path "$path")"
    BUILT_RECORDS+=("${leaf}${FIELD_SEP}${sha}${FIELD_SEP}${size}${FIELD_SEP}${role}${FIELD_SEP}${arch}${FIELD_SEP}${shown}")
    BUILT_PATHS+=("$path")
    BUILT_SHAS+=("$sha")
    log "artifact: $leaf sha256=$sha bytes=$size role=$role arch=$arch path=$shown"
    BUILT_NAMES+=("$leaf")
}

# ---------------------------------------------------------------------------
# the four build stages
# ---------------------------------------------------------------------------
# Each one: (1) refuses a declared input that is absent, with a code, before
# anything runs; (2) records not_run with the exact reason when the host, a
# tool or an input this script will not go and get is missing; (3) runs the
# upstream driver with the arguments its own code expects; (4) records the
# artifact it produced and its sha256.

# ---------------------------------------------------------------------------
# the OS root chain
# ---------------------------------------------------------------------------
# qemu_root_defconfig is qemu_defconfig plus the owner root chain: the original
# iPadOS OS volume mounted as the root, SystemOS as a union over it, and a Data
# volume at /private/var.  None of that is built by the kernel step -- it is made
# by the device repository's own scripts/build-os-root.py, which qemu_root_defconfig
# says so itself ("The archives are made outside the kernel step, from a kernel
# built with qemu_defconfig", configs/qemu_root_defconfig:12).
#
# So the chain is a stage of its own, and it has to run before the kernel that
# consumes it.  What it produces, and where:
#
#   .cache/firmware/owner-data/seed.json        the Data volume UUID
#                                            (qemu_root_defconfig:14 -- it is
#                                            not set in the config because every
#                                            seed has its own)
#   <tree>/build/native-virtio-block-verified-bundle/libNativeVirtioBlock.a
#   <tree>/build/verified-root-os-xnu-bundle/libVerifiedRootProbe.a
#                                            the two archives the config names
#                                            in CONFIG_XNU_NATIVE_VIRTIO_BLOCK_ARCHIVE
#                                            and CONFIG_XNU_VERIFIED_ROOT_ARCHIVE
#   <tree>/build/original-static-system-trust/original-static-system.bundle
#                                            the payload's --trust-cache
#   .cache/firmware/owner-data/owner-data-1g.dbr the payload's --data-ramdisk
#
# The two halves live in two different places on purpose, and that is upstream's
# layout rather than this script's choice: tree.py:assemble symlinks
# <tree>/.cache/firmware to <device>/.cache/firmware (so the seed and its UUID
# are shared by every tree and survive in the device repository) and makes
# <tree>/build a fresh directory per tree.  The paths below are therefore spelled
# with $DEVICE_DIR for the first group and $(tree_dir) for the second, which is
# the same split tree.py:48-56 draws.
#
# IT MUST BE RUN FROM THE TREE, NOT FROM THE DEVICE REPOSITORY.  build-os-root.py
# derives ROOT from __file__ (line 41) and qemu_esp.py derives WORK from
# ROOT.parent (line 14), so invoking $DEVICE_DIR/scripts/build-os-root.py would
# put WORK at <repo>/vendor and look for the kernel at vendor/kernel/, and would
# write its build/ outputs into the device repository.  The tree's own copy of
# the script resolves both correctly, which is why the README runs it as
# `cd out/qemu/tree && python3 scripts/build-os-root.py` (README:96).

#: The Data seed's report.  The volume UUID is read out of it and exported for
#: the kernel build, because qemu_root_defconfig does not carry it.  A function
#: rather than a variable for the same reason tree_dir() and work_dir() are: the
#: path is derived from $DEVICE_DIR, and a value captured before the caller has
#: finished setting that up is a stale path nobody notices until a stage looks
#: for a file that is not where the message says it is.
os_root_seed_json() { printf '%s' "$DEVICE_DIR/.cache/firmware/owner-data/seed.json"; }

# os_root_chain_paths -- the three files the owner root chain produces, one per line.
#
# One spelling, because there were about to be three: root_chain_present(),
# os_root_missing() and the new os_root_present() each named the seed and the two
# archives, and three copies of a path list is three places for it to drift --
# the divergence class this script spends its length avoiding (call-chain 7.4,
# standards R-1).  Each of the three is now a filter over this.
os_root_chain_paths() {
    printf '%s\n' \
        "$(os_root_seed_json)" \
        "$(tree_dir)/build/native-virtio-block-verified-bundle/libNativeVirtioBlock.a" \
        "$(tree_dir)/build/verified-root-os-xnu-bundle/libVerifiedRootProbe.a"
    return 0
}

# root_chain_present -- 0 when the kernel stage can build qemu_root_defconfig.
#
# Checks the two archives the config names plus the seed that carries the UUID:
# without all three the kernel build would fail on a missing input rather than on
# a wrong decision, and a not_run that names the missing file is the only honest
# report.  The trust cache and the data ramdisk are the payload's inputs and are
# checked by the stage that consumes them, not here.
root_chain_present() {
    local path
    while IFS= read -r path; do
        [[ -f "$path" ]] || return 1
    done < <(os_root_chain_paths)
    return 0
}

# os_root_missing -- the chain files that are absent, one per line.
os_root_missing() {
    local path
    while IFS= read -r path; do
        [[ -f "$path" ]] || printf '%s\n' "$(shown_path "$path")"
    done < <(os_root_chain_paths)
    return 0
}

# os_root_present -- the chain files that are on disk, one per line.
# The mirror of os_root_missing, for the one message that has to name what IS
# there: a reader of the ledger is trying to work out whether this run did the
# work or inherited it, and "not missing" is not an answer to that.
os_root_present() {
    local path
    while IFS= read -r path; do
        [[ -f "$path" ]] && printf '%s\n' "$(shown_path "$path")"
    done < <(os_root_chain_paths)
    return 0
}

# build-os-root -- the owner root chain, then what the kernel stage needs from it.
#   build-os-root.py:41-46   ROOT from __file__, --ipsw from $UNIXNU_IPSW
#   build-os-root.py:56-169  ten sub-steps, each skipped when its output exists
#   build-storage-abi.py:31  the first one needs the kernel step's kernel.macho
#   README:96-106            the chain, in order, and the UUID export
step_build_os_root() {
    local name='build-os-root'

    # (0) the chain may already have run, and if it has there is nothing here to
    #     add.  build-os-root.py skips every sub-step whose output exists (its own
    #     header says so, :56-169), so the only thing a second invocation of it
    #     buys is the two disk images' disk space again -- and on a GitHub macOS
    #     runner that is precisely what there is not room for.  Measured against
    #     the real image (the zip entries' file_size in
    #     iPad_Pro_HFR_17.7.11_21H461_Restore.ipsw): the OS volume is
    #     5,157,406,069 bytes and the SystemOS volume 3,303,014,400, so the
    #     chain's own inputs are 7.88 GiB before the build tree is counted, and
    #     DEFAULT_MIN_FREE_GB=8 against a runner's ~14 GiB leaves no room for the
    #     image as well.  These are the MEMBER sizes, which is what extraction
    #     costs and what then sits on disk; 044-76040-038.dmg is a UDIF container
    #     that decodes to 6,077,580,800 bytes, and hdiutil reads it in place, so
    #     the decoded size is never what occupies the filesystem here.
    #     So the workflow runs the chain *between* two invocations of this script
    #     -- the sequence README:96-98 spells out by hand and that step (4) below
    #     describes -- and deletes the volumes when it is done with them.
    #
    #     Recorded 'skipped' and not 'ran', because this invocation did not run
    #     it: the workflow step that did carries the chain's own log, and a 'ran'
    #     here would be this script claiming work it did not do.  What it does
    #     claim is that the chain's outputs are on disk, which is exactly what
    #     root_chain_present() checks rather than assumes -- and what the kernel
    #     stage below switches on.
    if root_chain_present; then
        local -a present=()
        local line
        while IFS= read -r line; do
            [[ -n "$line" ]] && present+=("$line")
        done < <(os_root_present)
        ledger_add "$name" 'skipped' \
            "the owner root chain is already on disk (${present[*]}): build-os-root.py skips every sub-step whose output exists, so re-running it here would spend the OS and SystemOS volumes' 7.88 GiB again for nothing. The workflow ran the chain between two invocations of this script (README:96-98) and deleted the volumes afterwards; build-kernel below builds qemu_root_defconfig from what the chain left"
        return 0
    fi

    # (1) the device repository's own script.  It is the chain: nothing here
    #     reimplements a step of it, because a second implementation of "sign
    #     every 4 KiB block of the OS image" is a second thing that can be wrong.
    local script
    script="$(tree_dir)/scripts/build-os-root.py"
    if [[ ! -f "$script" ]]; then
        ledger_add "$name" 'not_run' \
            "the device repository's build-os-root.py is not in the build tree ($(shown_path "$script")): the tree is assembled by 'unixnu defconfig', so build-kernel must have run first (tree.py:70-76 copies both repositories' scripts/ into the tree)"
        return 0
    fi

    # (2) host and tools.  hdiutil and diskutil attach the OS image read-only,
    #     grow the Data container and mount it to write SpringBoard's
    #     preferences (build-os-root.py:70,104-131); the host verifier links
    #     against OpenSSL 3, whose keg the script takes as --openssl-prefix
    #     (build-os-root.py:44-45,63-65).  Neither exists off macOS.  The keg is
    #     resolved by openssl_keg(), which is the same resolution the material
    #     delivery's encryption uses -- two spellings of it would be the
    #     divergence class this script keeps paying for.
    local openssl_prefix=''
    openssl_prefix="$(openssl_keg)"
    local -a need=('hdiutil' 'diskutil' 'python3')
    if [[ -n "$openssl_prefix" ]]; then
        apple_step_gate "$name" "${need[@]}" "$openssl_prefix" || return 0
    else
        # The keg is absent, so there is nothing to hand --openssl-prefix and the
        # script's own default (/opt/homebrew/...) would be wrong on an Intel Mac.
        # Reported rather than guessed at.
        apple_step_gate "$name" "${need[@]}" /opt/homebrew/opt/openssl@3 || return 0
    fi

    # (3) the IPSW.  The two disk images are extracted from it
    #     (build-os-root.py:58-62) and the System trust cache is read out of it
    #     (:164-168), so without a local image there is no OS volume to sign.
    if [[ -z "$IPSW_PATH" ]]; then
        ledger_add "$name" 'not_run' \
            'the OS and SystemOS images and the System trust cache all come out of the IPSW: pass --ipsw FILE (board.toml [ipsw] url is https and this script performs no network access, PRD 8.1)'
        return 0
    fi
    if [[ ! -f "$IPSW_PATH" ]]; then
        die 'artifact_missing' "the given IPSW does not exist: $IPSW_PATH" \
            "{\"ipsw\":\"$(json_escape "$IPSW_PATH")\"}" "$EXIT_FAILURE"
    fi

    # (4) the baseline kernel and payload.  This is the ordering constraint the
    #     vendor chain itself documents and that the plan cannot satisfy in one
    #     pass: build-storage-abi.py:31 refuses without WORK/kernel/kernel.macho,
    #     and it boots that kernel from the payload volume to observe the storage
    #     ABI (build-storage-abi.py:18).  Both are produced by build-kernel and
    #     build-payload, which the plan runs *after* this stage.
    #
    #     So on a fresh workspace this stage is not_run and build-kernel builds
    #     qemu_defconfig -- which is exactly the kernel the chain needs -- and a
    #     second invocation of this script, with that kernel on disk, runs the
    #     chain and then builds qemu_root_defconfig.  That is the sequence
    #     README:96-98 spells out by hand, and it is recorded as not_run rather
    #     than papered over, because the alternative is a kernel built from a
    #     chain that was never observed.
    local kernel payload
    kernel="$(work_dir)/kernel/kernel.macho"
    payload="$(work_dir)/payload/payload.img"
    if [[ ! -f "$kernel" ]]; then
        ledger_add "$name" 'not_run' \
            "the chain's first sub-step boots the kernel step's kernel.macho and refuses without it (build-storage-abi.py:31): $(shown_path "$kernel") is absent, so this stage needs a qemu_defconfig kernel built first. Run this script again after build-kernel and build-payload have produced it (README:96-98)"
        return 0
    fi
    if [[ ! -f "$payload" ]]; then
        ledger_add "$name" 'not_run' \
            "the storage-ABI observation boots the candidate from the payload volume (build-storage-abi.py:18, qemu_esp.py:27): $(shown_path "$payload") is absent, so build-payload must have produced it first"
        return 0
    fi

    # (5) run, from the tree.  The script skips every sub-step whose output
    #     already exists (build-os-root.py:56-169), so a second invocation spends
    #     its time on what is actually missing rather than redoing the chain.
    local os_root_log="$OUT_DIR/${name}.driver.log"
    log "+ $PY $(shown_path "$script") --ipsw <given> --openssl-prefix $openssl_prefix (cwd $(tree_dir))"
    if ! ( cd "$(tree_dir)" && "$PY" "$script" --ipsw "$IPSW_PATH" \
            ${openssl_prefix:+--openssl-prefix "$openssl_prefix"} ) 2>&1 | tee "$os_root_log"; then
        ledger_add "$name" 'failed' \
            "build-os-root.py failed; see $(shown_path "$os_root_log")"
        return 1
    fi

    # (6) what the kernel stage needs, published.  The UUID is read out of the
    #     seed's own report rather than re-derived, because qemu_root_defconfig:14
    #     says it comes from the environment and every seed has its own -- a
    #     value guessed here would mount the wrong Data volume.
    local uuid=''
    if [[ -f "$(os_root_seed_json)" ]]; then
        uuid="$("$PY" -c 'import json,sys; print(json.load(open(sys.argv[1]))["volume_uuid"])' \
            "$(os_root_seed_json)" 2>>"$os_root_log")"
    fi
    if [[ ! "$uuid" =~ ^[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}$ ]]; then
        ledger_add "$name" 'failed' \
            "the chain ran but $(shown_path "$(os_root_seed_json)") carries no volume_uuid the kernel build could use; see $(shown_path "$os_root_log")"
        return 1
    fi
    local -a missing=()
    local line
    while IFS= read -r line; do
        [[ -n "$line" ]] && missing+=("$line")
    done < <(os_root_missing)
    if (( ${#missing[@]} > 0 )); then
        ledger_add "$name" 'failed' \
            "the chain ran but did not produce: ${missing[*]}"
        return 1
    fi
    log "os root: XNU_OWNER_DATA_VOLUME_UUID=$uuid (from $(shown_path "$(os_root_seed_json)"))"
    ledger_add "$name" 'ran' \
        "build-os-root.py: the owner root chain; the kernel stage below builds qemu_root_defconfig with XNU_OWNER_DATA_VOLUME_UUID from $(shown_path "$(os_root_seed_json)")"
    return 0
}

# build_buttons_sink_stub STEP -- the optional board button sink, as an archive.
#
# NativeHidInput declares `native_buttons_set_sink` weak_import and guards every
# use with &symbol, which is the idiom for a symbol a board may not provide.
# This board provides no button driver, so nothing defines it -- and measured on
# run 40222638377, the first kernel that links NativeHidInput.late.o at all, the
# undefined reference is a hard link error rather than null:
#
#     Undefined symbols for architecture arm64:
#       "_native_buttons_set_sink", referenced from: NativeHidInput::start(...)
#
# The sibling `native_touch_set_sink` is defined by the device repository's
# package (TouchState.cpp:23), so it resolves; that contrast is what says the
# problem is the missing definition and not the weak attribute as such.
#
# A no-op body is exactly the semantics the driver asked for: the sink is
# called and nothing happens, which is what "no buttons" means.  It is built
# here rather than in the device repository because that repository is pinned
# and re-cloned every run, and a local edit would not survive (the same
# reasoning as the chain step's display forcing).
#
# The archive is handed to the driver's link through XNU_EXTRA_LD_ARCHIVES,
# which build-xnu-4k-baseline.sh:732 appends to the kernel's own archives --
# an interface the vendor script already exposes for exactly this shape.
build_buttons_sink_stub() {
    local step="$1"
    # Under the tree, not under OUT_DIR, because the config names the archive
    # with the board's own {tree} placeholder (qemu_defconfig:29) and a second
    # spelling of the same directory is how the two drift apart.
    local out="$(tree_dir)/build/buttons-sink"
    local archive="$out/libButtonsSink.a"
    if [[ -f "$archive" ]]; then
        return 0
    fi
    mkdir -p "$out"
    local source="$out/ButtonsSink.c"
    # The signature is the driver's own (NativeHidInput.cpp:15): a callback and
    # a context.  Both are ignored -- the sink exists so the reference resolves,
    # and this board has nothing to report through it.
    cat >"$source" <<'STUB'
/* The board button driver this board does not have.

NativeHidInput.cpp:15 declares native_buttons_set_sink weak_import and guards
every call with &symbol, so a board with no hardware buttons is supposed to
leave it undefined and the driver is supposed to see null.  Measured on run
40222638377: the undefined reference in the objcopy-staged NativeHidInput.late.o
is a hard link error instead, so the reference is satisfied here with a body
that does nothing -- behaviourally identical to absent, and the only lever this
repository holds, because both the declaration and the staging live in pinned
public repositories.
*/
void native_buttons_set_sink(void (*sink)(void *, unsigned int), void *context) {
    (void)sink;
    (void)context;
}
STUB
    local object="$out/ButtonsSink.o"
    local log="$OUT_DIR/${step}.buttons-sink.log"
    # --sdk iphoneos and the version floor, the same shape the device
    # repository's own drivers are built with (build-native-legacy-display.py:40
    # uses `xcrun --sdk iphoneos clang -arch arm64 -mkernel
    # -miphoneos-version-min=17.0`), so the object the kernel link sees is the
    # same platform and deployment target as the object referencing it.
    if ! xcrun --sdk iphoneos clang -arch arm64 -miphoneos-version-min=17.0 \
            -c "$source" -o "$object" 2>&1 | tee "$log"; then
        log "buttons sink: the stub did not compile; see $log"
        return 1
    fi
    xcrun ar rcs "$archive" "$object" 2>&1 | tee -a "$log"
    if [[ ! -f "$archive" ]]; then
        log "buttons sink: no archive was produced; see $log"
        return 1
    fi
    log "buttons sink: $(basename "$archive") built (the optional sink NativeHidInput imports)"
    return 0
}

# name_buttons_sink_in_config STEP -- put the stub on the kernel link's archives.
#
# THE ENVIRONMENT IS NOT THE INTERFACE, and that was measured rather than
# assumed.  The first attempt exported XNU_EXTRA_LD_ARCHIVES, which
# build-xnu-4k-baseline.sh:732 does append to the kernel's archives -- and run
# 40229046208 built the archive and still failed the link on the same symbol,
# because the config's own CONFIG_XNU_EXTRA_LD_ARCHIVES (qemu_defconfig:29 names
# libLinkStubs.a) becomes that environment variable, overwriting the export.
# The generated out/<device>/.config is therefore where the archive is named.
#
# It is APPENDED to the value the board already carries rather than replacing
# it: replacing it would drop libLinkStubs.a and trade one undefined-symbol
# failure for three (_mockfs_mountroot, _mockfs_vfsops,
# _mockfs_vnodeop_opv_desc -- measured on run 40067448940).
#
# The file being changed is the generated one `unixnu defconfig` just copied
# from the board, so this is a divergence from the pin, recorded as one -- the
# same shape, and the same reasoning, as CONFIG_XNU_BUILD_ARCHIVES=y below: the
# runner clones vendor/ fresh at the locked commit every run, so a local edit
# would not survive and committing one would make the pin exist twice.
name_buttons_sink_in_config() {
    local step="$1"
    local config generated archive relative
    config="$(work_dir)/.config"
    archive="$(tree_dir)/build/buttons-sink/libButtonsSink.a"
    if [[ ! -f "$config" ]]; then
        die 'artifact_missing'             "the generated kernel config $config is absent, so the button sink cannot be named on the link."             "{"config":\"$(json_escape "$config")\"}" "$EXIT_FAILURE"
    fi
    if [[ ! -f "$archive" ]]; then
        die 'artifact_missing'             "the button sink archive $archive is absent; build_buttons_sink_stub did not run."             "{"archive":\"$(json_escape "$archive")\"}" "$EXIT_FAILURE"
    fi
    relative="{tree}/build/buttons-sink/libButtonsSink.a"
    if grep -qF "$relative" "$config"; then
        return 0
    fi
    generated="$("$PY" - "$config" "$relative" <<'PYEDITOR'
import sys
from pathlib import Path

config, relative = Path(sys.argv[1]), sys.argv[2]
key = "CONFIG_XNU_EXTRA_LD_ARCHIVES="
lines = config.read_text(encoding="utf-8").splitlines()
for index, line in enumerate(lines):
    if line.startswith(key):
        value = line[len(key):].strip().strip('"')
        if relative in value.split():
            sys.exit(0)
        lines[index] = f'{key}"{value} {relative}"'
        config.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"config: {key} now also names {relative}")
        sys.exit(0)
print(f"config: {key} is not in the generated config, so nothing was appended", file=sys.stderr)
sys.exit(1)
PYEDITOR
)" || {
        log "buttons sink: $generated"
        return 1
    }
    log "buttons sink: $generated"
    CONFIG_DIVERGENCE="${CONFIG_DIVERGENCE:+$CONFIG_DIVERGENCE; }$relative appended to CONFIG_XNU_EXTRA_LD_ARCHIVES in the generated .config"
    return 0
}

# build-kernel -- 'unixnu defconfig <name>' then 'unixnu build kernel'.
#   cli.py:89-101  cmd_defconfig copies configs/<name> to out/<device>/.config
#   cli.py:123-129 cmd_build runs kernel.build() then kernel.prelink()
#   kernel.py:71-102 kernel.build(): git, make, clang, cmake, ninja, unifdef and
#                  xcodebuild, then scripts/build-xnu-4k-baseline.sh
#   kernel.py:105-137 kernel.prelink(): out/<device>/kernel/kernel.macho, and it
#                  logs the sha256 of what it wrote
step_build_kernel() {
    local name='build-kernel'
    # (1) inputs.  The defconfig is named by board.toml [kernel] and must exist
    # in the device repository; the driver refuses a build without it
    # (cli.py:123-124, config.py:105-108).
    if [[ -z "$DEFCONFIG" ]]; then
        die 'config_invalid' \
            "board.toml of $DEVICE_DIR has no [kernel] defconfig." \
            "{\"device\":\"$(json_escape "$DEVICE_DIR")\"}" "$EXIT_USAGE"
    fi
    # (1b) which defconfig.  board.toml [kernel] names qemu_defconfig, which is
    #      the right answer for every run that has no owner root chain -- and the
    #      wrong one for a run that has it, because qemu_root_defconfig is
    #      qemu_defconfig plus the chain and the two are not interchangeable: the
    #      guest either mounts the owner-signed OS volume as its root or stops at
    #      "Failed to mount root device" (README:179).
    #
    #      The switch is on disk rather than on the in-process flag
    #      step_build_os_root set, so a kernel built in a run where the chain was
    #      already on disk from an earlier one still gets it.  It is not a second
    #      spelling of the board's choice: the board's value is the default, and
    #      this only overrides it when the chain it asks for exists.
    local defconfig="$DEFCONFIG" defconfig_origin="board.toml [kernel] defconfig"
    if root_chain_present; then
        defconfig='qemu_root_defconfig'
        defconfig_origin='the owner root chain build-os-root produced'
        log "kernel: the root chain is present, so building $defconfig ($defconfig_origin)"
    else
        log "kernel: no owner root chain on disk, so building $defconfig ($defconfig_origin)"
    fi
    if [[ ! -f "$DEVICE_DIR/configs/$defconfig" ]]; then
        die 'artifact_missing' \
            "defconfig not found: $DEVICE_DIR/configs/$defconfig" \
            "{\"defconfig\":\"$(json_escape "$defconfig")\",\"expected\":\"$(json_escape "$DEVICE_DIR/configs/$defconfig")\"}" \
            "$EXIT_FAILURE"
    fi
    # kernel.prelink() takes the original kernelcache from --kernelcache, from
    # board.toml [kernel.prelink] kernelcache, or out of the IPSW
    # (kernel.py:111-114).  This board names no kernelcache file and its
    # [ipsw] default is an https URL, so without a local input the step would
    # have to download one.  It records not_run instead.
    if [[ -z "$KERNELCACHE_PATH" && -z "$IPSW_PATH" ]]; then
        ledger_add "$name" 'not_run' \
            'the prelink step needs the original kernelcache: pass --kernelcache FILE or --ipsw FILE (board.toml [ipsw] url is https and this script performs no network access, PRD 8.1)'
        return 0
    fi

    # (2) host and tools, exactly the list kernel.py:73-75 checks.
    local -a need=('git' 'make' 'clang' 'cmake' 'ninja' 'unifdef' 'xcodebuild')
    log_keg
    apple_step_gate "$name" "${need[@]}" || return 0

    # (3b) the optional button sink.  qemu_root_defconfig is qemu_defconfig plus
    #      CONFIG_XNU_NATIVE_LEGACY_DISPLAY, and that config pulls in
    #      libNativeLegacyDisplay.late.a with -Wl,-force_load -- so this is the
    #      first kernel that links NativeHidInput.late.o at all.  Measured on
    #      run 40222638377, the first run to reach the kernel link:
    #
    #        Undefined symbols for architecture arm64:
    #          "_native_buttons_set_sink", referenced from:
    #              NativeHidInput::start(IOService*) in ...(NativeHidInput.late.o)
    #
    #      The driver declares it weak_import (NativeHidInput.cpp:15) and tests
    #      it with &symbol before calling, which is the idiom for "optional".
    #      Its sibling native_touch_set_sink is DEFINED in the device
    #      repository's package (TouchState.cpp:23), so it resolves; nothing in
    #      either pinned repository defines the buttons one, and the undefined
    #      reference in the objcopy-staged .late.o is a hard error rather than
    #      null.  This board has no hardware button driver, so the optional sink
    #      is absent by design -- a no-op definition is behaviourally identical
    #      to absent, and it is the only lever this repository holds: the
    #      staging that loses the flag and the declaration itself both live in
    #      pinned public repositories.
    # (3) run.  The defconfig first, because build kernel refuses without it.
    local -a extra=()
    if [[ -n "$KERNELCACHE_PATH" ]]; then extra+=(--kernelcache "$KERNELCACHE_PATH"); fi
    if [[ -n "$IPSW_PATH" ]]; then extra+=(--ipsw "$IPSW_PATH"); fi
    # (3a) the Data volume UUID.  qemu_root_defconfig:14 does not set it and says
    #      why -- every seed has its own -- so the kernel build reads it from the
    #      environment and this is where it comes from.  Exported rather than
    #      passed as an argument because that is the interface the config names,
    #      and because run_driver builds the command line itself.
    if [[ "$defconfig" == 'qemu_root_defconfig' ]]; then
        local uuid=''
        if [[ -f "$(os_root_seed_json)" ]]; then
            uuid="$("$PY" -c 'import json,sys; print(json.load(open(sys.argv[1]))["volume_uuid"])' \
                "$(os_root_seed_json)" 2>>"$OUT_DIR/${name}.driver.log")"
        fi
        if [[ ! "$uuid" =~ ^[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}$ ]]; then
            ledger_add "$name" 'not_run' \
                "the root chain is present but $(shown_path "$(os_root_seed_json)") carries no volume_uuid, and qemu_root_defconfig:14 takes it from the environment: the Data volume could not be mounted at /private/var"
            return 0
        fi
        export XNU_OWNER_DATA_VOLUME_UUID="$uuid"
        log "kernel: XNU_OWNER_DATA_VOLUME_UUID exported from $(shown_path "$(os_root_seed_json)")"
    fi
    if ! run_driver "$name" 'defconfig' "$defconfig" ${extra[@]+"${extra[@]}"}; then
        ledger_add "$name" 'failed' "unixnu defconfig $defconfig failed; see $OUT_DIR/${name}.driver.log"
        return 1
    fi

    # (3b) the optional button sink, AFTER the defconfig and not before it: the
    #      thing being edited is the generated .config that `unixnu defconfig`
    #      has just written, so naming the archive earlier would find no file to
    #      edit.  (The first draft put it here-and-before, and would have died on
    #      its own artifact_missing.)
    if [[ "$defconfig" == 'qemu_root_defconfig' ]]; then
        if build_buttons_sink_stub "$name"; then
            name_buttons_sink_in_config "$name" || return 1
        fi
    fi

    # (3b) supply the archive opt-in the board's defconfig omits.
    #
    # Measured on a real macOS runner (run 40067448940): every XNU translation
    # unit compiles, and the link then fails on
    #
    #   _mockfs_mountroot / _mockfs_vfsops / _mockfs_vnodeop_opv_desc
    #       (referenced from _vfstbllist in vfs_conf.o)
    #   _native_legacy_display_probe / _sheng_pmgr_run
    #       (referenced from _bsd_init in bsd_init.o)
    #
    # and the driver then reports `test -f "$CRYPTO_ARCHIVE" failed`.  The cause
    # is not the link: kernel.py's build_archives() returns immediately unless
    # the resolved config carries XNU_BUILD_ARCHIVES, and qemu_defconfig declares
    # CONFIG_XNU_NATIVE_AES, CONFIG_XNU_SOURCE_CORECRYPTO14,
    # CONFIG_XNU_SOURCE_MOCKFS and CONFIG_XNU_EXTRA_LD_ARCHIVES=...libLinkStubs.a
    # without ever opting in.  It asks for archives it never builds.
    #
    # This is a defect in the pinned device repository, not in this project, and
    # it is worked around here rather than by editing vendor/: the runner clones
    # vendor/ fresh at the locked commit, so a local edit would not survive and
    # committing one would make the pin exist twice.  The file being changed is
    # the *generated* out/<device>/.config, which `unixnu defconfig` just copied
    # from the board -- so this is a divergence from the pin, recorded as one.
    local generated_config
    generated_config="$(work_dir)/.config"
    if [[ -f "$generated_config" ]] && ! grep -q '^CONFIG_XNU_BUILD_ARCHIVES=' \
            "$generated_config"; then
        {
            printf '\n# Added by build-macos.sh: the board defconfig declares the\n'
            printf '# archives below without opting into building them, so the kernel\n'
            printf '# link has no mockfs, corecrypto or link-stubs input.  Divergence\n'
            printf '# from the pinned device repository, recorded here deliberately.\n'
            printf 'CONFIG_XNU_BUILD_ARCHIVES=y\n'
        } >>"$generated_config"
        log "config: added CONFIG_XNU_BUILD_ARCHIVES=y (the board defconfig omits it)"
        # Appended, not assigned: the button sink records its own divergence
        # above, and an assignment here would erase it from the manifest.
        CONFIG_DIVERGENCE="${CONFIG_DIVERGENCE:+$CONFIG_DIVERGENCE; }CONFIG_XNU_BUILD_ARCHIVES=y added to the generated .config"
    fi

    if ! run_driver "$name" 'build' 'kernel' ${extra[@]+"${extra[@]}"}; then
        ledger_add "$name" 'failed' "unixnu build kernel failed; see $OUT_DIR/${name}.driver.log"
        return 1
    fi

    # (4) the artifact prelink writes, and the sha256 it logged.
    local macho
    macho="$(work_dir)/kernel/kernel.macho"
    record_artifact "$macho" 'kernel' 'aarch64'
    ledger_add "$name" 'ran' \
        "unixnu build kernel; $(logs_dir)/prelink.log carries the sha256 prelink logged"
    return 0
}

# build-bootloader -- 'unixnu build package', then the device repository's own
# DarwinBoot builder.
#   cli.py:133-134  cmd_build runs package.build() for the package step
#   package.py:21-31 package.build(): the EDK II build of package/ under
#                  out/<device>/package, which also leaves the CLANGPDB tool
#                  links under out/<device>/toolchain
#   board.toml:85-86 of the pinned device repository: "No [firmware]: QEMU runs
#                  its own EDK II AARCH64 firmware, which has no DarwinBoot", so
#                  the bootloader is built by the device repository's
#                  scripts/build-darwinboot-efi.py, which run-qemu.py:83-96
#                  calls before it boots anything.
step_build_bootloader() {
    local name='build-bootloader'

    if [[ ! -f "$DRIVER" ]]; then
        die 'artifact_missing' "the build driver is missing: $DRIVER" \
            "{\"driver\":\"$(json_escape "$DRIVER")\"}" "$EXIT_FAILURE"
    fi

    # (2) host and tools.  package.py:24 checks clang; the EDK II build of the
    # device's DarwinBoot additionally needs python3 and make, and the driver's
    # own prepare() needs git.
    local -a need=('git' 'clang' 'make' 'python3')
    log_keg
    apple_step_gate "$name" "${need[@]}" || return 0

    # (3) the package first: it assembles the build tree (tree.py:40-76) and
    # leaves the CLANGPDB tool links build-darwinboot-efi.py requires.
    if ! run_driver "$name" 'build' 'package'; then
        ledger_add "$name" 'failed' "unixnu build package failed; see $OUT_DIR/${name}.driver.log"
        return 1
    fi
    local script
    script="$(tree_dir)/scripts/build-darwinboot-efi.py"
    if [[ ! -f "$script" ]]; then
        die 'artifact_missing' \
            "the device repository's DarwinBoot builder is not in the build tree: $script" \
            "{\"script\":\"$(json_escape "$script")\"}" "$EXIT_FAILURE"
    fi
    log "+ $PY $script"
    if ! "$PY" "$script" >"$OUT_DIR/${name}.darwinboot.log" 2>&1; then
        ledger_add "$name" 'failed' \
            "build-darwinboot-efi.py failed; see $OUT_DIR/${name}.darwinboot.log"
        return 1
    fi
    tail -n 3 "$OUT_DIR/${name}.darwinboot.log" >&2 || true

    # (4) the driver image the payload loads (board.toml [payload] loader).
    record_artifact "$(tree_dir)/build/darwinboot-efi/DarwinBoot.efi" 'bootloader' 'aarch64'

    # (5) the UEFI application the firmware starts.  Step (3) built it
    #     (package.py:21-31 writes <work>/package/Build/Out) but the payload does
    #     NOT carry it: payload.py:173-177 writes EFI/UniXNU/unixnu.toml naming
    #     Payloads/DarwinBoot.efi as a driver, and run-qemu.py:93-95 is what puts
    #     UniXNU.efi at EFI/BOOT/BOOTAA64.EFI.  So this is the one output of this
    #     step that no other step produces, and without it there is nothing for
    #     the firmware to start -- measured on run 40081850615, where
    #     artifact-manifest.json recorded it (93,696 bytes, sha256
    #     59b7aa748848328bc88d363d57180c9faba491eccfd5e7847565e033d4858016) and
    #     the tree artifact carrying the bytes was later deleted, leaving the
    #     record of a file that no longer exists anywhere.
    #
    #     Globbed rather than spelled out: the directory is AARCH64-<target> and
    #     the target is the driver's own default (package.py:21, DEBUG), so a
    #     literal path would be a second place that knows it.
    #
    #     Read in a loop, not with mapfile: mapfile is bash 4+ and macOS ships
    #     /bin/bash 3.2 (see the plan below), so the glob is expanded into the
    #     same idiom the rest of this script uses.
    local -a unixnu_efi=()
    local candidate
    for candidate in "$(work_dir)"/package/Build/Out/AARCH64-*/UniXNU.efi; do
        [[ -f "$candidate" ]] && unixnu_efi+=("$candidate")
    done
    if (( ${#unixnu_efi[@]} == 0 )); then
        # ledger_add, not die: by this point step (3) has run and the kernel, the
        # DarwinBoot image and the manifest records all exist.  `die` is for a
        # refusal *before* anything runs -- the script's own header says so -- and
        # using it here would discard build-report.json, artifact-manifest.json
        # and every artifact record on precisely the failure where the evidence
        # matters most.  Every other postcondition failure in this same function
        # (`unixnu build package failed`) records failed and returns 1, which
        # stops the plan identically through stage_failed.
        ledger_add "$name" 'failed' \
            "the UEFI application the firmware starts was not built: $(work_dir)/package/Build/Out/AARCH64-*/UniXNU.efi (package.py:21-31; 'unixnu build package' ran in step (3) and exited 0)"
        log "bootloader: FAIL no UniXNU.efi under $(work_dir)/package/Build/Out; see the ledger entry"
        return 1
    fi
    if (( ${#unixnu_efi[@]} > 1 )); then
        die 'evidence_incomplete' \
            "${#unixnu_efi[@]} UniXNU.efi candidates were built and there is no way to say which one boots: ${unixnu_efi[*]}" \
            "{\"step\":\"$name\"}" "$EXIT_FAILURE"
    fi

    # (6) ...and it has to be an *application*.  Measured on Windows QEMU 11.1.0
    #     with the EDK II firmware: a driver at EFI/BOOT/BOOTAA64.EFI gets "The
    #     image is not an application." from the shell and "failed to load
    #     Boot0001 \"UEFI Misc Device\" ... Not Found" from BDS -- a message that
    #     names the device and not the reason, so it reads like a missing file
    #     while `ls FS0:\EFI\BOOT` shows it there.  DarwinBoot.efi and
    #     DarwinBootValidation.efi are both subsystem 11 for exactly that reason
    #     (UniXNU LoadImage's them as drivers), which makes publishing the wrong
    #     one an easy mistake the firmware reports badly.  UniXNU.inf:13 is
    #     MODULE_TYPE = UEFI_APPLICATION, so the check is against what the
    #     package declares, not a guess.
    local program="$OUT_DIR/${name}.subsystem.py"
    if ! cat >"$program" <<'PY'
"""Check the image that will sit at EFI/BOOT/BOOTAA64.EFI is an application.

The firmware is the authority here and it reports the failure badly (see the
caller), so the check happens before the bundle is published rather than in the
first boot log.  ``pe_subsystem`` is the same reader ``unipad.host.unixnu_boot``
refuses with locally, so the runner and the Windows host cannot disagree about
what the firmware will do with the file.
"""
import sys
from pathlib import Path

from unipad.host.unixnu_boot import (
    PE_SUBSYSTEM_APPLICATION,
    PE_SUBSYSTEM_NAMES,
    pe_subsystem,
)

image = Path(sys.argv[1])
subsystem = pe_subsystem(image)
name = PE_SUBSYSTEM_NAMES.get(subsystem, subsystem) if subsystem is not None else "not a PE32+ image"
# Flushed by hand: the failure below goes to stderr, and without this the two
# streams interleave in the wrong order in the log the runner keeps.
print(f"bootloader: {image.name} {image.stat().st_size} bytes, PE subsystem {subsystem} ({name})", flush=True)
if subsystem != PE_SUBSYSTEM_APPLICATION:
    print(
        f"bootloader: FAIL EFI/BOOT/BOOTAA64.EFI must be a UEFI application "
        f"(subsystem {PE_SUBSYSTEM_APPLICATION}); the firmware refuses anything else "
        f"with 'The image is not an application.'",
        file=sys.stderr,
    )
    sys.exit(1)
PY
    then
        log "bootloader: the subsystem check could not be written: $program"
        return 1
    fi
    if ! run_unipad "$program" "${unixnu_efi[0]}" 2>&1 | tee "$OUT_DIR/${name}.subsystem.log"; then
        tail -n 5 "$OUT_DIR/${name}.subsystem.log" >&2 || true
        ledger_add "$name" 'failed' \
            "UniXNU.efi is not a UEFI application; see $(shown_path "$OUT_DIR/${name}.subsystem.log")"
        return 1
    fi
    record_artifact "${unixnu_efi[0]}" 'bootloader' 'aarch64'

    ledger_add "$name" 'ran' \
        'unixnu build package + build-darwinboot-efi.py (this board declares no [firmware], board.toml:85-86) + UniXNU.efi, the UEFI application the firmware starts'
    return 0
}

# build-payload -- 'unixnu build payload': the FAT ESP volume the machine boots.
#   cli.py:135-137  cmd_build runs payload.build() for the payload step
#   payload.py:84-193 payload.build(): stages EFI/UniXNU/Payloads/kernel.macho
#                  (patched for the panic screen when board.toml [payload]
#                  panic_screen is set, payload.py:130-142), runs the board's
#                  [payload.adt] tool to write kernel.macho.adt beside it
#                  (payload.py:149-171), writes EFI/UniXNU/unixnu.toml naming
#                  Payloads/DarwinBoot.efi as a [[driver]] when [payload] loader
#                  is "driver" (payload.py:173-177), and formats the volume with
#                  mtools (payload.py:56-64).
#
# WHY IT IS OPT-IN (--payload): see the note in plan_steps.  The short version is
# that a milestone must not change meaning for a caller that never asked for an
# ESP, and that this is the one stage that needs a Homebrew package the rest of
# the build does not.
#
# WHAT IT NEEDS THAT THE OTHER STAGES DO NOT: qemu-system-aarch64 and mtools.
# make-qemu-adt.py:93-101 dumps the device tree of the machine it is about to
# describe BY RUNNING QEMU, and payload.py:56-58 requires mformat and mcopy to
# write the volume.  Both are installed here when they are absent, because a
# macOS runner with Apple's toolchain has neither by default and the step would
# otherwise fail for a reason that has nothing to do with the build.
#
# ---------------------------------------------------------------------------
# THE TWO FILES THIS STAGE CANNOT DO WITHOUT, AND WHY THEY ARE OPTIONAL HERE
# ---------------------------------------------------------------------------
# 'unixnu build payload' takes --trust-cache and --data-ramdisk, and this script
# did not pass either.  That is not a small omission: build-os-root.py:26-27
# records what the missing trust cache costs, in the device repository's own
# words --
#
#     build-original-system-trust.py: the original static and System trust caches
#     as one bundle, the payload's --trust-cache. Without it AMFI refuses to run
#     launchd (exit reason namespace 9, EXEC, code 8, SECURITY_POLICY).
#
# -- and the same script's LAST line (build-os-root.py:174) is the command the
# chain says to run next:
#
#     unixnu build payload ... --trust-cache {trust} --data-ramdisk {seed}
#
# So a payload built without them is a volume that boots a kernel which cannot
# start a userland.  Every acceptance criterion downstream of "launchd is PID 1"
# sits behind it.
#
# They are OPTIONAL ARGUMENTS to this script for one reason only, and it is an
# ordering reason rather than a judgement about whether they matter: the owner
# root chain is what PRODUCES them, and it runs BETWEEN the workflow's two build
# passes.  The first pass therefore has neither and must not be refused for
# that.  The second pass has both, and a second pass that does not forward them
# rebuilds the same dead ESP with a kernel that can finally mount a root volume
# -- which is the worst possible outcome, because it looks like progress.
#
# So the shape is: accept the paths, forward them when they are given, and say
# in the log which of the two the run has.  What the stage must NOT do is
# invent a trust cache of its own: the chain's static module is pinned by
# sha256 (build-os-root.py:159-162, da88460e...) and board.toml [payload]
# trust_cache_sha256 lists the two the board accepts, so a substitute would be
# refused by payload.py:106 anyway.
step_build_payload() {
    local name='build-payload'

    if [[ ! -f "$DRIVER" ]]; then
        die 'artifact_missing' "the build driver is missing: $DRIVER" \
            "{\"driver\":\"$(json_escape "$DRIVER")\"}" "$EXIT_FAILURE"
    fi

    # (0) the board's own [payload] block, in the log.  read_board_fields read it
    #     and the verifier below reads it again, so this is where the two halves
    #     are named together: a reader of the log sees what this run's board
    #     asked for without opening board.toml, and a board that changes shows up
    #     here rather than only inside the verifier's output.
    local trust_caches=0
    if [[ -n "$PAYLOAD_TRUST_CACHE_SHA256" ]]; then
        trust_caches="$(printf '%s' "$PAYLOAD_TRUST_CACHE_SHA256" \
            | tr ',' '\n' | grep -c '[^[:space:]]')"
    fi
    log "payload: board [payload] volume=$PAYLOAD_VOLUME size=${PAYLOAD_SIZE_MIB}MiB dram_size=$PAYLOAD_DRAM_SIZE loader=$PAYLOAD_LOADER panic_screen=$PAYLOAD_PANIC_SCREEN trust_cache_pins=$trust_caches skip_setup_tool=${PAYLOAD_SKIP_SETUP_TOOL:-<none>}"

    # (1) inputs.  The volume is a copy of the prelinked kernel plus a device
    #     tree, so build-kernel and build-bootloader must have produced theirs
    #     first; the driver refuses a missing one with a message about its own
    #     default (payload.py:91-92), and a not_run here names this run instead.
    local kernel darwinboot
    kernel="$(work_dir)/kernel/kernel.macho"
    if [[ ! -f "$kernel" ]]; then
        ledger_add "$name" 'not_run' \
            "the prelinked kernel is missing ($kernel): build-kernel did not produce it, so the payload has nothing to carry (payload.py:91-92)"
        return 0
    fi
    # The ESP's unixnu.toml names Payloads/DarwinBoot.efi as a driver but does
    # NOT contain it: run-qemu.py:83-96 copies it into the volume at boot time.
    # So the boot input set is only complete with the bootloader on disk, and a
    # payload without it is a volume that cannot start.
    darwinboot="$(tree_dir)/build/darwinboot-efi/DarwinBoot.efi"
    if [[ ! -f "$darwinboot" ]]; then
        ledger_add "$name" 'not_run' \
            "DarwinBoot.efi is missing ($darwinboot): the volume's unixnu.toml loads it as a driver and run-qemu.py:83-96 copies it in at boot, so build-bootloader must have produced it first"
        return 0
    fi

    # (2) host.  The volume itself is pure Python plus mtools, but its inputs are
    #     the kernel and the bootloader, both of which need the Apple toolchain,
    #     so the host gate is the same one the other stages use.
    local -a need=('git' 'make' 'python3')
    apple_step_gate "$name" "${need[@]}" || return 0

    # (2b) the panic screen's font header, BEFORE the driver is allowed to die on
    #     it.  board.toml [payload] panic_screen = true (UniXNU-qemu/board.toml:94),
    #     so payload.py:130-136 runs the device repo's patch-xnu-entry-probe.py,
    #     which compiles scripts/xnu-panic-screen.c -- and that file's ONLY include
    #     is "Font.h" (xnu-panic-screen.c:294), taken from
    #     (UNIXNU_UEFI or <tree>/uefi-sheng)/Silicon/Silicium/SiliciumPkg/Library/
    #     FrameBufferSerialPortLib (patch-xnu-entry-probe.py:183).  The assembled
    #     tree never contains uefi-sheng/ -- tree.py:assemble creates only
    #     drivers/ kits/ patches/ refer/ build/ .cache/ package/ scripts/ -- so
    #     without either spelling the font directory does not exist at all.
    #
    #     Measured on run 40094234507 (and again on 40096928333): the step reached
    #     the driver and died in clang with "fatal error: 'Font.h' file not
    #     found", which names the include and not the reason -- the same shape as
    #     the firmware's "The image is not an application."  So it is checked here,
    #     where the ledger can say what is missing and what it costs.
    #
    #     WHY THERE ARE TWO CHANNELS, and why this script uses the flag.  Both
    #     reach the patcher: cli.py:136 sets ctx.uefi from ctx.option('uefi',
    #     'UNIXNU_UEFI'), which reads --uefi first and the UNIXNU_UEFI
    #     environment variable second (config.py:110-117), and payload.py:142
    #     then runs the patcher with UNIXNU_UEFI=str(ctx.uefi).  Measured on this
    #     host against the real config.py: with UNIXNU_UEFI exported and no flag,
    #     ctx.uefi is that path and the patcher receives it; with neither,
    #     ctx.uefi is None and the patcher receives ''.  So the earlier advice
    #     "point UNIXNU_UEFI at a Mu-Silicium checkout" was workable -- it was
    #     simply never done, by anything.
    #
    #     --uefi is what this script passes anyway, for three reasons: it lands
    #     in the driver's own argv.log so the run's evidence names the checkout
    #     instead of an inherited variable nobody recorded; need_uefi()
    #     (cli.py:67-73) reads the same option for the firmware and boot-image
    #     stages, so one spelling serves every consumer; and a flag is testable
    #     where an exported variable is ambient state.
    #
    #     What it costs when it is missing: the panic screen only.  The entry
    #     probe (stage bars, --no-reset) is the other half of the same patch and
    #     is wanted with either setting (payload.py:128-129), so a kernel patched
    #     without the font still boots; it just cannot draw a panic message.  The
    #     stage is recorded failed rather than worked around, because the board
    #     asked for the screen and the file it needs is not on this host.
    if [[ "$PAYLOAD_PANIC_SCREEN" == 'yes' ]]; then
        # --uefi first, then the patch script's own fallback.  The fallback is
        # spelled the same way patch-xnu-entry-probe.py:183 spells it
        # (ROOT/'uefi-sheng', where ROOT is the tree the script was copied into),
        # so the path this check names is the path the compiler would be given.
        local uefi_root="$UEFI_DIR"
        [[ -n "$uefi_root" ]] || uefi_root="$(tree_dir)/uefi-sheng"
        # The lock and upstream must agree about where the font is.  A lock that
        # names another path is not a shorter route to the same file: it means
        # one of the two moved, and the compiler still uses FONT_RELATIVE.
        if [[ -n "$LOCK_FONT_PATH" && "$LOCK_FONT_PATH" != "$FONT_RELATIVE" ]]; then
            ledger_add "$name" 'failed' \
                "the lock and the panic-screen patcher disagree about where Font.h is: $LOCK_PATH uefi_sheng.font_header.path is '$LOCK_FONT_PATH', patch-xnu-entry-probe.py:183 puts it at '$FONT_RELATIVE'. Re-pin the lock against the upstream script; this check cannot pick one for you"
            log "payload: FAIL the locked font path '$LOCK_FONT_PATH' is not '$FONT_RELATIVE'; see the ledger entry"
            return 1
        fi
        local font="$uefi_root/$FONT_RELATIVE"
        if [[ ! -f "$font" ]]; then
            ledger_add "$name" 'failed' \
                "the panic screen's font header is not on this host: $font (xnu-panic-screen.c:294 includes \"Font.h\" and patch-xnu-entry-probe.py:183 takes it from UNIXNU_UEFI or <tree>/uefi-sheng, and neither exists here). The font lives in the Mu-Silicium checkout pinned as uefi_sheng in $LOCK_PATH; pass --uefi DIR pointing at it, or export UNIXNU_UEFI=DIR (cli.py:136 reads either), and the workflow passes vendor/uefi-sheng"
            log "payload: FAIL $font is missing; see the ledger entry"
            return 1
        fi
        # The file is not enough: it must be the bytes the lock promised.  A
        # checkout at another commit can carry a Font.h that compiles and is not
        # this one, and a panic screen drawn from someone else's glyph table is
        # not reproducible.  The digest is recorded rather than derived here
        # (sources.lock.json uefi_sheng.font_header.sha256) so the lock stays the
        # single place that knows it.
        local font_sha=''
        font_sha="$(sha256_of "$font" 2>/dev/null || true)"
        if [[ -n "$LOCK_FONT_SHA256" ]]; then
            if [[ ! "$font_sha" =~ $SHA256_PATTERN ]]; then
                ledger_add "$name" 'failed' \
                    "could not compute the SHA-256 of the panic screen's font header: $font"
                log "payload: FAIL $font is unreadable; see the ledger entry"
                return 1
            fi
            if [[ "$font_sha" != "$LOCK_FONT_SHA256" ]]; then
                ledger_add "$name" 'failed' \
                    "the panic screen's font header is not the one the lock pins: $font has sha256 $font_sha, sources.lock.json uefi_sheng.font_header.sha256 is $LOCK_FONT_SHA256 (uefi_sheng.commit $LOCK_UEFI_SHENG_COMMIT). Re-pin uefi_sheng or restore the pinned checkout; building the panic screen from another glyph table is not this build"
                log "payload: FAIL $font sha256=$font_sha != locked $LOCK_FONT_SHA256; see the ledger entry"
                return 1
            fi
        fi
        if [[ -n "$LOCK_UEFI_SHENG_COMMIT" ]]; then
            local font_head=''
            font_head="$(head_of "$uefi_root")"
            log "payload: panic-screen font $font sha256=${font_sha:-<none>}${font_head:+ (checkout at ${font_head:0:12}, lock pins ${LOCK_UEFI_SHENG_COMMIT:0:12})}"
        else
            log "payload: panic-screen font $font sha256=${font_sha:-<none>} (no digest pinned in $LOCK_PATH; the file's presence is all that was checked)"
        fi
    fi

    # (3) the two Homebrew packages the step cannot run without.  Neither is a
    #     preflight requirement (see the header), so they are satisfied here.
    #     The status is captured rather than read from $? inside the branch:
    #     `if ! f; then case "$?"` sees the negation's status, not the
    #     function's, so every outcome would take the same arm.
    local tools_status=0
    payload_tools_ready || tools_status=$?
    if (( tools_status == 2 )); then
        # An environment blocker, not a failure of the build: recorded not_run,
        # which keeps the run's verdict honest without stopping the plan.
        ledger_add "$name" 'not_run' \
            'qemu-system-aarch64 and/or mtools are absent and there is no brew on this runner to install them with; make-qemu-adt.py:93-101 dumps the machine device tree through QEMU and payload.py:56-58 writes the volume with mformat/mcopy'
        return 0
    fi
    if (( tools_status != 0 )); then
        ledger_add "$name" 'failed' \
            "brew install qemu mtools failed; see $(shown_path "$OUT_DIR/${name}.tools.log")"
        return 1
    fi
    local qemu_bin
    qemu_bin="$(adt_qemu_path)"
    if [[ -z "$qemu_bin" ]]; then
        ledger_add "$name" 'not_run' \
            'qemu-system-aarch64 was installed but is still not on PATH and not in a Homebrew prefix; make-qemu-adt.py:93-101 cannot dump the machine device tree without it'
        return 0
    fi
    log "payload: qemu $qemu_bin"

    # (4) the platform seed.  Three sources, in the order the operator would
    #     expect: the flag, the driver's own environment spelling
    #     (payload.py:119 reads UNIXNU_UNIQUE_CHIP_ID), and finally a derivation
    #     from the pinned device-repo commit that is kept in this run's
    #     workspace.  board.toml [payload.adt] unique_chip_id = "required", so
    #     there is no fourth option of "none".
    local seed="$UNIQUE_CHIP_ID" seed_origin='--unique-chip-id' seed_commit=''
    if [[ -z "$seed" ]]; then
        seed_commit="$LOCK_DEVICE_COMMIT"
        [[ -n "$seed_commit" ]] || seed_commit="$(head_of "$DEVICE_DIR")"
        if ! seed="$(derive_platform_seed 2>>"$OUT_DIR/${name}.seed.log")" \
                || [[ ! "$seed" =~ ^[0-9a-f]{16}$ ]]; then
            seed=''
            ledger_add "$name" 'not_run' \
                'the platform seed is not stored in any repository and cannot be derived from the pinned device-repo commit: pass --unique-chip-id HEX (board.toml [payload.adt] unique_chip_id = "required")'
            return 0
        fi
        seed_origin="derived from the pinned device-repo commit ${seed_commit:0:12} (unipad.host.adt.derive_seed)"
        persist_platform_seed "$seed" "$seed_origin" "$seed_commit"
    else
        seed_commit="$(head_of "$DEVICE_DIR")"
        persist_platform_seed "$seed" "$seed_origin" "$seed_commit"
    fi
    log "payload: seed $seed_origin, sha256 $PLATFORM_SEED_SHA256, kept at $(shown_path "$(platform_seed_path)")"

    # (5) run.  The kernel is passed rather than left to the driver's default
    #     (payload.py:90) so the ledger and the log name the file that was used.
    #     UNIXNU_QEMU_ACCEL is exported for this invocation only: the tree's
    #     timebase follows it (make-qemu-adt.py:19, make-dt.py:71-76) and
    #     run-qemu.py:120-125 refuses a tree whose timebase does not match the
    #     accelerator it is about to run.  The payload target is the lock's own
    #     accelerator (validate_lock refuses a mismatch), so it is the right one.
    #
    #     --uefi is passed when this run has one.  It is the channel this script
    #     prefers, and the one whose use is recorded: cli.py:136 sets ctx.uefi
    #     from --uefi (or from UNIXNU_UEFI, config.py:110-117) and payload.py:142
    #     forwards it to the patcher as UNIXNU_UEFI, so the driver's argv.log
    #     names the checkout the font came from.  It is omitted rather than
    #     passed empty when the caller gave none, because `--uefi ''` would make
    #     ctx.option() fall through to the environment anyway and would put a
    #     misleading empty argument in the log.
    local -a uefi_args=()
    if [[ -n "$UEFI_DIR" ]]; then
        uefi_args+=(--uefi "$UEFI_DIR")
    fi
    # (4b) the owner root chain's two outputs.  Same shape as --uefi and for the
    #      same reason: omitted rather than passed empty, so the driver's argv.log
    #      carries what this run actually had.  The difference from --uefi is
    #      what their absence MEANS, which is why they get a log line of their
    #      own -- an ESP built without the trust cache is a volume that boots a
    #      kernel AMFI will not let exec launchd (build-os-root.py:26-27), and
    #      that has to be visible in the log rather than inferable from the
    #      absence of a flag.
    local -a root_args=()
    # A counter, not ${#root_args[@]}: macOS ships /bin/bash 3.2 (see the plan
    # note below), where ${#arr[@]} on an empty array under `set -u` is an
    # unbound-variable error.  The script's other empty-array expansions use the
    # ${arr+"${arr[@]}"} form for the same reason; this one needs a COUNT, and a
    # counter is the version that works everywhere.
    local root_count=0
    if [[ -n "$TRUST_CACHE_PATH" ]]; then
        root_args+=(--trust-cache "$TRUST_CACHE_PATH")
        root_count=$((root_count + 1))
    fi
    if [[ -n "$DATA_RAMDISK_PATH" ]]; then
        root_args+=(--data-ramdisk "$DATA_RAMDISK_PATH")
        root_count=$((root_count + 1))
    fi
    # The GPU addon is NOT part of the owner root chain, so it is deliberately
    # outside root_count: it is a separate axis, and folding it in would make
    # "the trust cache and the Data ramdisk are both supplied" a sentence about
    # something else.  Its absence is recorded for the same reason the trust
    # cache's is -- measured, not inferred: without the blob the kernel has
    # nothing to materialise /private/var/ngpu from, native_gpu_addon_mount
    # fails its first vnode_lookup with ENOENT (stage 1 / status 2), and
    # native_gop_ready stays 0 no matter what else is right.
    if [[ -n "$GPU_ADDON_PATH" ]]; then
        root_args+=(--gpu-addon "$GPU_ADDON_PATH")
        log "payload: the GPU addon is supplied; the kernel will materialise /private/var/ngpu before it mounts"
    else
        log "payload: no GPU addon; the kernel will create no /private/var/ngpu and the addon mount will fail its first lookup with ENOENT"
    fi
    if (( root_count == 2 )); then
        log "payload: the owner root chain's trust cache and Data ramdisk are both supplied; this ESP can start a userland"
    elif (( root_count == 0 )); then
        # The first pass's normal state.  Recorded rather than silent, because
        # the same silence on the SECOND pass is the defect this branch exists
        # to make visible -- and a reader cannot tell the two apart from the
        # build report alone.
        log "payload: no trust cache and no Data ramdisk (the owner root chain has not run in this pass); AMFI will refuse launchd from this volume"
    else
        log "payload: only one of the trust cache and the Data ramdisk was supplied; see --trust-cache/--data-ramdisk"
    fi
    log "+ unixnu build payload -D $DEVICE_DIR --out $UNIXNU_OUT --kernel $kernel --unique-chip-id <seed sha256 $PLATFORM_SEED_SHA256>${uefi_args:+ ${uefi_args[*]}}${root_args:+ ${root_args[*]}}"
    if ! ( export UNIXNU_QEMU_ACCEL="$TARGET"
           run_driver "$name" 'build' 'payload' --kernel "$kernel" --unique-chip-id "$seed" \
               ${uefi_args+"${uefi_args[@]}"} \
               ${root_args+"${root_args[@]}"} ); then
        ledger_add "$name" 'failed' "unixnu build payload failed; see $OUT_DIR/${name}.driver.log"
        return 1
    fi

    # (6) read the volume back.  An exit code of 0 is not evidence: the driver
    #     formats the image with mtools and reports success before anything has
    #     looked inside it, so every file the boot needs is checked against the
    #     driver's own record (payload.json, payload.py:185-190) and against
    #     unipad.host.adt.verify_adt, which is the check that names a tree that
    #     parses but carries no platform identity.
    local image report esp
    image="$(work_dir)/payload/payload.img"
    report="$(work_dir)/payload/payload.json"
    esp="$OUT_DIR/payload-esp"
    if ! verify_payload_image "$image" "$report" "$esp" "$seed" "$TARGET"; then
        ledger_add "$name" 'failed' \
            "the payload volume did not verify; see $(shown_path "$OUT_DIR/${name}.verify.log")"
        return 1
    fi

    # (7) the artifacts.  The image is the deliverable; the device tree is
    #     recorded from the copy that was lifted out of the volume, because that
    #     is the file a downloader can open and the one the guest actually reads.
    record_artifact "$image" 'firmware' 'aarch64'
    record_artifact "$esp/EFI/UniXNU/Payloads/kernel.macho.adt" 'devicetree' 'aarch64'
    record_artifact "$esp/EFI/UniXNU/unixnu.toml" 'auxiliary' 'aarch64'
    PAYLOAD_ADT_PATH="$esp/EFI/UniXNU/Payloads/kernel.macho.adt"
    ledger_add "$name" 'ran' \
        "unixnu build payload; the volume was read back and every boot input verified against payload.json and unipad.host.adt.verify_adt (seed $seed_origin, sha256 $PLATFORM_SEED_SHA256)"
    return 0
}

# payload_tools_ready -- make sure qemu-system-aarch64 and mtools are on PATH.
#
# Returns 0 when they are (or were just installed), 1 when brew was tried and
# failed -- its output is in the step's tools.log and is echoed to stderr, since
# a Homebrew diagnostic is the whole diagnosis -- and 2 when there is no brew to
# try at all.
#
# The two Homebrew prefixes are consulted by hand after the install, for the
# reason adt_qemu_path documents: the runner publishes a freshly-installed keg to
# $GITHUB_PATH for LATER steps, which does not help the shell that is running
# right now.
payload_tools_ready() {
    local log_file="$OUT_DIR/build-payload.tools.log"
    local -a want=() still=()
    command -v qemu-system-aarch64 >/dev/null 2>&1 || want+=('qemu')
    if ! command -v mformat >/dev/null 2>&1 || ! command -v mcopy >/dev/null 2>&1; then
        want+=('mtools')
    fi
    if (( ${#want[@]} == 0 )); then
        log 'payload tools: qemu-system-aarch64, mformat and mcopy are on PATH'
        return 0
    fi
    if ! command -v brew >/dev/null 2>&1; then
        log "payload tools: ${want[*]} absent and there is no brew on this runner to install them with"
        return 2
    fi
    log "+ brew install ${want[*]}"
    if ! brew install "${want[@]}" 2>&1 | tee "$log_file"; then
        printf 'brew install %s failed; its output follows:\n' "${want[*]}" >&2
        cat "$log_file" >&2 || true
        return 1
    fi
    command -v qemu-system-aarch64 >/dev/null 2>&1 || still+=('qemu-system-aarch64')
    command -v mformat >/dev/null 2>&1 || still+=('mformat')
    command -v mcopy  >/dev/null 2>&1 || still+=('mcopy')
    if (( ${#still[@]} > 0 )); then
        log "payload tools: still absent after brew install: ${still[*]}"
        return 1
    fi
    log "payload tools: installed ${want[*]} (log: $(shown_path "$log_file"))"
    return 0
}

# verify_payload_image IMAGE REPORT ESP_DIR SEED TARGET -- read the volume back
# and check everything the boot needs is inside it.
#
# The ESP is extracted the way the boot script extracts it -- `mcopy -s -n -i
# payload ::/EFI` (run-qemu.py:76) -- and the Python check that follows compares
# it against the driver's own record and against this repository's verify_adt.
# Returns 0 when every check passes; the log carries what was found either way.
verify_payload_image() {
    local image="$1" report="$2" esp="$3" seed="$4" target="$5"
    local log_file="$OUT_DIR/build-payload.verify.log"
    if [[ ! -s "$image" ]]; then
        log "payload: $image is missing or empty"
        return 1
    fi
    if [[ ! -s "$report" ]]; then
        log "payload: the driver's own record is missing or empty: $report (payload.py:190)"
        return 1
    fi
    if ! command -v mcopy >/dev/null 2>&1; then
        log 'payload: mcopy is not on PATH, so the volume cannot be read back'
        return 1
    fi
    rm -rf -- "$esp"
    if ! mkdir -p -- "$esp"; then
        log "payload: cannot create $esp"
        return 1
    fi
    if ! MTOOLS_SKIP_CHECK=1 mcopy -s -n -i "$image" '::/EFI' "$esp" \
            >"$OUT_DIR/build-payload.esp.log" 2>&1; then
        log "payload: the ESP could not be read back; see $(shown_path "$OUT_DIR/build-payload.esp.log")"
        return 1
    fi
    # The verifier is written to a file rather than fed to the interpreter on
    # stdin: a heredoc belongs to the LAST command of a pipeline, so
    # `run_unipad - ... <<PY | tee log` would hand the program to tee and leave
    # the interpreter with an empty stdin.  It stays on disk as evidence either
    # way, next to the log it produced.
    local program="$OUT_DIR/build-payload.verify.py"
    if ! cat >"$program" <<'PY'
"""Read the payload volume back and check every boot input is inside it.

The volume is what the machine boots, so "the driver exited 0" is not evidence:
the image is formatted with mtools and reported as written before anything has
looked inside it.  Every number below is compared against the driver's own
record (payload.json, payload.py:185-190) or against this repository's
verify_adt, which is the check that names a tree that parses but carries no
platform identity -- a guest with no IOPlatformUUID, which surfaces much later
as userland that cannot start rather than as a boot failure.
"""
import hashlib
import json
import sys
import tomllib
from pathlib import Path

image = Path(sys.argv[1])
report_path = Path(sys.argv[2])
esp = Path(sys.argv[3])
seed = sys.argv[4]
device_dir = Path(sys.argv[5])
target = sys.argv[6]

problems = []


def want(condition, message):
    if not condition:
        problems.append(message)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


report = json.loads(report_path.read_text(encoding='utf-8'))
board = tomllib.loads((device_dir / 'board.toml').read_text(encoding='utf-8'))
spec = board.get('payload', {})

# --- the volume itself -----------------------------------------------------
blob = image.read_bytes()
want(len(blob) > 0, f'{image.name} is empty')
want(report.get('payload_bytes') == len(blob),
     f'{image.name} is {len(blob)} bytes; payload.json records {report.get("payload_bytes")}')
want(report.get('payload_sha256') == hashlib.sha256(blob).hexdigest(),
     f'{image.name} does not hash to the payload_sha256 payload.json recorded')
# The board's own size, checked against the bytes on disk rather than restated.
size = spec.get('size_mib')
if isinstance(size, int):
    want(len(blob) == size << 20,
         f'{image.name} is {len(blob)} bytes; board.toml [payload] size_mib is {size} ({size << 20} bytes)')
want(report.get('panic_screen') == bool(spec.get('panic_screen')),
     f'board.toml [payload] panic_screen is {spec.get("panic_screen")!r}; the driver reported {report.get("panic_screen")!r}')
want(report.get('skip_setup') is False,
     'the driver reported a Data seed this run never supplied')

# --- what is inside the volume --------------------------------------------
payloads = esp / 'EFI/UniXNU/Payloads'
kernel = payloads / 'kernel.macho'
adt = payloads / 'kernel.macho.adt'
config = esp / 'EFI/UniXNU/unixnu.toml'
for path in (kernel, adt, config):
    relative = path.relative_to(esp).as_posix()
    want(path.is_file(), f'the ESP does not carry {relative}')
    if path.is_file():
        want(path.stat().st_size > 0, f'{relative} is empty')

if not problems:
    want(digest(kernel) == report.get('payload_kernel_sha256'),
         'the kernel inside the ESP does not hash to payload.json payload_kernel_sha256')
    want(digest(adt) == report.get('adt_sha256'),
         'the device tree inside the ESP does not hash to payload.json adt_sha256')

    parsed = tomllib.loads(config.read_text(encoding='utf-8'))
    entries = [entry.get('path') for entry in parsed.get('entry', [])]
    drivers = [driver.get('path') for driver in parsed.get('driver', [])]
    want('Payloads/kernel.macho' in entries,
         f'unixnu.toml names no boot entry for the kernel: {entries}')
    # board.toml [payload] loader decides whether DarwinBoot travels inside the
    # volume as a driver or inside a firmware volume (payload.py:173).  This
    # board declares no [firmware] (board.toml:85-86), so "driver" is the only
    # spelling that can boot -- and the file itself is copied in at boot time by
    # run-qemu.py:83-96, which is why it is not in the volume.
    if spec.get('loader', 'firmware') == 'driver':
        want('Payloads/DarwinBoot.efi' in drivers,
             f'unixnu.toml does not load DarwinBoot as a driver: {drivers}')
    else:
        want(not drivers,
             f'unixnu.toml loads {drivers} but board.toml [payload] loader is not "driver"')

    # --- the device tree this machine boots -------------------------------
    from unipad.host.adt import read_board_adt, verify_adt

    try:
        record = verify_adt(adt, read_board_adt(device_dir), seed=seed)
    except Exception as error:  # UniPadError names what the tree lacks
        problems.append(f'verify_adt refused the device tree: {error}')
        record = None
    if record is not None:
        print(f'payload: device tree {record["bytes"]} bytes, sha256 {record["sha256"]}')
        print(f'payload:   model {record["model"]!r} target-type {record["target_type"]!r} '
              f'chip-id {record["chip_id"]}')
        if 'unique_chip_id' in record:
            print(f'payload:   unique-chip-id {record["unique_chip_id"]:x}')
        print(f'payload:   timebase {record["timebase_hz"]} Hz')
        # run-qemu.py:120-125 refuses a tree whose timebase does not match the
        # accelerator it is about to run; make-dt.py:71 is where the TCG value
        # is written.  hvf reads the host counter instead and cannot be
        # predicted here, so it is only recorded.
        if target == 'tcg':
            want(record.get('timebase_hz') == 62500000,
                 f'the device tree has a {record.get("timebase_hz")} Hz timebase and tcg needs '
                 '62500000 (run-qemu.py:120-125)')

    print(f'payload: ESP kernel.macho {kernel.stat().st_size} bytes, sha256 {digest(kernel)}')
    print(f'payload: ESP kernel.macho.adt {adt.stat().st_size} bytes, sha256 {digest(adt)}')
    print(f'payload: unixnu.toml entries={entries} drivers={drivers}')
    print(f'payload: volume {spec.get("volume")!r} {len(blob)} bytes, '
          f'dram_size {spec.get("dram_size")!r}, panic_screen {spec.get("panic_screen")!r}')
    allowed = spec.get('trust_cache_sha256') or []
    packed = report.get('trust_cache_sha256')
    if packed:
        want(packed in allowed,
             f'the driver packed a trust cache ({packed}) that board.toml [payload] does not accept')
    else:
        # Recorded, not asserted: the board's pins are an allow-list the driver
        # applies when a cache IS supplied (payload.py:105-106), and this run
        # supplies none, so there is nothing to check one against.
        print(f'payload: no trust cache in the volume (board.toml allows {len(allowed)})')

if problems:
    for problem in problems:
        print(f'payload: FAIL {problem}', file=sys.stderr)
    sys.exit(1)
print('payload: verified against payload.json and unipad.host.adt.verify_adt')
PY
    then
        log "payload: the verifier could not be written: $program"
        return 1
    fi
    if ! run_unipad "$program" "$image" "$report" "$esp" "$seed" "$DEVICE_DIR" "$target" \
            2>&1 | tee "$log_file"; then
        tail -n 25 "$log_file" >&2 || true
        return 1
    fi
    return 0
}
# build-devicetree -- the board's own device tree out of the pinned IPSW, then
# the Apple-format tree this machine boots with.
#   cli.py:156-171  cmd_ipsw extracts a component and checks it against
#                   board.toml [ipsw.sha256] (ipsw.py:140-171)
#   python3 -m unipad.host.adt
#                   board.toml [payload.adt] -> the make-qemu-adt.py argument
#                   set, the same mapping payload.py:149-171 performs, then a
#                   read-back of the tree that was written (adt.py:494-618)
step_build_devicetree() {
    local name='build-devicetree'

    # (1) the board's original device tree.  Two routes to it, and the second is
    # why the first is not the only option:
    #
    #   --ipsw FILE       the driver extracts it itself (unixnu ipsw fetch
    #                     DeviceTree), which needs the whole 6.8 GB image on disk
    #                     for one ~1 MB file;
    #   --devicetree FILE the acquisition step already extracted and published
    #                     it, the same way it publishes the kernelcache.
    #
    # Measured on a real macOS runner (run 40077120172, stage M4): this step was
    # the only not_run, because the acquisition step publishes the kernelcache and
    # deletes the image by design, so --ipsw was never available.  The extraction
    # is the same work either way -- board.toml [ipsw] fetch names "DeviceTree"
    # and BuildManifest.plist resolves it to a member -- so doing it once in the
    # acquisition step and handing the result over is strictly less work than
    # keeping 6.8 GB alive across the whole build.
    #
    # What is NOT skipped is the existence check: a stage that reports a file it
    # did not produce is the defect record_artifact() exists to catch, so the
    # pre-extracted path is checked exactly as the driver's answer is.
    local extracted=''
    if [[ -n "$DEVICETREE_PATH" ]]; then
        if [[ ! -f "$DEVICETREE_PATH" ]]; then
            die 'artifact_missing' \
                "the given device tree does not exist: $DEVICETREE_PATH" \
                "{\"devicetree\":\"$(json_escape "$DEVICETREE_PATH")\"}" "$EXIT_FAILURE"
        fi
        extracted="$DEVICETREE_PATH"
        log "devicetree: using the one the acquisition step extracted ($(shown_path "$extracted"))"
    elif [[ -n "$IPSW_PATH" ]]; then
        # (2) host and tools.  ipsw.kernelcache() is not on this path, but the
        # extraction is the driver's own code and needs the interpreter and git.
        local -a need=('git' 'python3')
        apple_step_gate "$name" "${need[@]}" || return 0

        # (3) the board's original device tree, extracted and checked against the
        # board's own pin.  Measured on this host with the local IPSW: it works, so
        # this is the one sub-step that is genuinely exercisable off macOS.
        if ! run_driver "$name" 'ipsw' 'fetch' 'DeviceTree' --ipsw "$IPSW_PATH"; then
            ledger_add "$name" 'failed' \
                "unixnu ipsw fetch DeviceTree failed; see $OUT_DIR/${name}.driver.log"
            return 1
        fi
        # The driver prints the path it extracted as its last line (ipsw.py:171);
        # that is the driver's own answer, so it is used rather than re-derived from
        # the IPSW's member naming.
        extracted="$(tail -n 1 "$OUT_DIR/${name}.driver.log" 2>/dev/null | tr -d '\r')"
        if [[ ! -f "$extracted" ]]; then
            ledger_add "$name" 'failed' \
                "unixnu ipsw fetch DeviceTree printed no extractable path (last line: ${extracted:-<empty>})"
            return 1
        fi
    else
        ledger_add "$name" 'not_run' \
            'the device tree comes out of the pinned IPSW: pass --devicetree FILE (already extracted) or --ipsw FILE (the driver extracts it; the default of board.toml [ipsw] is an https URL and this script performs no network access, PRD 8.1)'
        return 0
    fi

    record_artifact "$extracted" 'devicetree' 'aarch64'
    ledger_add "$name" 'ran' \
        'the board device tree, checked against board.toml [ipsw.sha256] (ipsw.py:161-163)'

    # (3b) the Apple-format tree the payload actually boots with.  Its own
    # ledger entry, because it has its own fate: it is the one sub-step in this
    # entry point that needs no Apple toolchain at all (pure Python plus one QEMU
    # call), so it is gated on the three things it genuinely needs and nothing
    # else.  Each gate names the exact reason, because a run that reports
    # not_run for a reason that is not the real one is worse than one that
    # reports nothing (PRD 7.4).
    local adt_name='build-devicetree/adt'
    local adt_log="$OUT_DIR/${adt_name//\//-}.adt.log"
    # build-payload generates this tree too, inside the ESP, and it is the one the
    # guest actually boots.  Running the tool a second time would spend paid macOS
    # minutes on a QEMU dump whose result is already on disk, and would leave two
    # different files both called kernel.macho.adt -- so when the payload step has
    # produced and verified one, this sub-step is recorded skipped, naming the file
    # that was verified.  'skipped' is not 'not_run': the tree exists, and a run in
    # which it is missing still reports ok=false.
    if [[ -n "$PAYLOAD_ADT_PATH" ]]; then
        ledger_add "$adt_name" 'skipped' \
            "build-payload already generated and verified it inside the ESP: $(shown_path "$PAYLOAD_ADT_PATH")"
        return 0
    fi
    if [[ -z "$ADT_TOOL" ]]; then
        ledger_add "$adt_name" 'not_run' \
            "board declares no [payload.adt] tool in board.toml of $DEVICE_DIR, so the Apple-format device tree is not produced for this board"
        return 0
    fi

    # (i) the platform seed.  Given, or derived from the pin and kept in the
    #     run's workspace -- never in a repository, never in Git.  The refusal
    #     below names WHICH of the three ways to get one failed, because "pass
    #     --unique-chip-id" is only actionable once the reader knows the
    #     derivation was not available either.
    local seed="$UNIQUE_CHIP_ID" seed_origin='--unique-chip-id' seed_commit=''
    if [[ -z "$seed" ]]; then
        seed_commit="$LOCK_DEVICE_COMMIT"
        [[ -n "$seed_commit" ]] || seed_commit="$(head_of "$DEVICE_DIR")"
        local why=''
        if [[ ! -f "$REPO_ROOT/src/unipad/host/adt.py" ]]; then
            # The module is the derivation AND the argument mapping, so without it
            # there is no seed and no tool invocation either.
            why='this checkout carries no src/unipad/host/adt.py, which is what derives it'
        elif [[ ! "$seed_commit" =~ ^[0-9a-fA-F]{7,64}$ ]]; then
            why='the pinned device-repo commit is unknown (the lock names none and the checkout has no HEAD)'
        elif ! seed="$(derive_platform_seed 2>>"$adt_log")" \
                || [[ ! "$seed" =~ ^[0-9a-f]{16}$ ]]; then
            seed=''
            why="unipad.host.adt.derive_seed failed; see $(shown_path "$adt_log")"
        fi
        if [[ -z "$seed" ]]; then
            ledger_add "$adt_name" 'not_run' \
                "the platform seed is not stored in any repository: pass --unique-chip-id HEX (board.toml [payload.adt] unique_chip_id = \"required\"); it could not be derived from the pinned device-repo commit because $why"
            return 0
        fi
        seed_origin="derived from the pinned device-repo commit ${seed_commit:0:12} (unipad.host.adt.derive_seed)"
        persist_platform_seed "$seed" "$seed_origin" "$seed_commit"
        log "adt seed: derived from the device pin ${seed_commit:0:12}; sha256 $PLATFORM_SEED_SHA256, kept at $(shown_path "$(platform_seed_path)")"
    else
        persist_platform_seed "$seed" '--unique-chip-id' "$(head_of "$DEVICE_DIR")"
        log "adt seed: given as --unique-chip-id; sha256 $PLATFORM_SEED_SHA256, kept at $(shown_path "$(platform_seed_path)")"
    fi

    # (ii) qemu-system-aarch64.  make-qemu-adt.py:93-101 dumps the device tree of
    #      the machine it is about to describe by running
    #        qemu-system-aarch64 -M virt,...,dumpdtb=<file> -m <dram> -smp <cpus>
    #      and refuses without it (:95, "brew install qemu"), so this is a real
    #      input of the sub-step and not an optional extra.  It is installed here
    #      rather than in require_tools() because nothing else in the build uses
    #      it: a preflight refusal would stop the kernel, the bootloader and the
    #      manifest for the sake of one Homebrew package.  make-qemu-adt.py:82
    #      also invokes python3 by bare name; macOS ships /usr/bin/python3, so
    #      unlike Windows there is nothing to shim for that.
    local qemu_status=0 qemu_bin
    ensure_qemu "$adt_name" || qemu_status=$?
    if (( qemu_status == 2 )); then
        return 0    # ensure_qemu recorded not_run with the reason
    fi
    if (( qemu_status != 0 )); then
        return 1    # ... and failed, naming the brew log
    fi
    qemu_bin="$(adt_qemu_path)"
    log "adt: qemu $qemu_bin"

    # (iii) the tree.  make-qemu-adt.py lives in the DEVICE repository but
    #       invokes scripts/qemu-entry/make-dt.py, which only UniXNU carries
    #       (make-qemu-adt.py:82), so neither repository alone can run it.
    #       unipad.host.adt.prepare_tree merges both scripts/ directories into
    #       $(tree_dir) exactly the way tree.py:assemble does upstream, the device
    #       repository copied last so a device's spelling of a script wins.
    local adt
    adt="$(work_dir)/kernel/kernel.macho.adt"
    log "+ $PY -m unipad.host.adt --device $DEVICE_DIR --unixnu $UNIXNU_DIR --tree $(tree_dir) --qemu $qemu_bin --out $adt --seed <sha256 $PLATFORM_SEED_SHA256> --log $(shown_path "$adt_log")"
    # The seed is not echoed on the command line this script prints.  It is a
    # device identity rather than a secret (adt.py:62-68), but it is deliberately
    # in no repository and the build log is uploaded as evidence, so what is
    # printed is its sha256; the value itself is in the run's own platform-seed
    # and in platform-seed.json's provenance record.
    # stderr goes to the same log as stdout, so a traceback from the module lands
    # next to the tool's own output instead of in the middle of the build log.
    if ! run_unipad -m unipad.host.adt \
            --device "$DEVICE_DIR" \
            --unixnu "$UNIXNU_DIR" \
            --tree "$(tree_dir)" \
            --qemu "$qemu_bin" \
            --out "$adt" \
            --seed "$seed" \
            --log "$adt_log" 2>>"$adt_log"; then
        ledger_add "$adt_name" 'failed' \
            "unipad.host.adt failed; see $(shown_path "$adt_log") (it runs $ADT_TOOL with the whole [payload.adt] argument set and verifies the tree it wrote)"
        return 1
    fi
    record_artifact "$adt" 'devicetree' 'aarch64'
    ledger_add "$adt_name" 'ran' \
        "$ADT_TOOL through unipad.host.adt: the whole [payload.adt] set, seed $seed_origin (sha256 $PLATFORM_SEED_SHA256)"
    return 0
}

# assemble-image -- 'unixnu bootimg'.
#   cli.py:142-153  cmd_bootimg: need_uefi() first (cli.py:67-73), then the
#                   firmware volume, the device tree and the optional ramdisk
#   bootimg.py:71-114 bootimg.build(): gzip(BootShim + firmware volume) with the
#                   device tree appended, then unpacked again and compared
step_assemble_image() {
    local name='assemble-image'

    # (1) the inputs, refused with a code before anything runs.  need_uefi()
    # requires a Mu-Silicium checkout carrying Resources/Scripts/mkbootimg.py
    # (cli.py:67-73) and fd_path() reads board.toml [firmware] fd
    # (firmware.py:17-19).
    if [[ "$BOARD_HAS_FIRMWARE" != 'yes' ]]; then
        ledger_add "$name" 'not_run' \
            "board.toml of $DEVICE_DIR declares no [firmware], so there is no firmware volume to pack: measured on this host, 'unixnu bootimg --uefi DIR' on this board dies with KeyError: 'firmware' at firmware.py:18 (QEMU runs its own EDK II AARCH64 firmware, board.toml:85-86)"
        return 0
    fi
    if [[ -z "$UEFI_DIR" ]]; then
        ledger_add "$name" 'not_run' \
            'the boot image is packed from a Mu-Silicium checkout: pass --uefi DIR (cli.py:67-73 need_uefi)'
        return 0
    fi
    if [[ ! -f "$UEFI_DIR/Resources/Scripts/mkbootimg.py" ]]; then
        die 'config_invalid' \
            "$UEFI_DIR is not a Mu-Silicium checkout (no Resources/Scripts/mkbootimg.py)." \
            "{\"uefi\":\"$(json_escape "$UEFI_DIR")\"}" "$EXIT_USAGE"
    fi
    if [[ -z "$DTB_PATH" ]]; then
        ledger_add "$name" 'not_run' \
            'the boot image needs a compiled device tree: pass --dtb FILE (or UNIXNU_DTB); bootimg.build() refuses a missing one (bootimg.py:77-79)'
        return 0
    fi
    if [[ -z "$FD_PATH_IN" ]]; then
        ledger_add "$name" 'not_run' \
            'the boot image needs a firmware volume: pass --fd FILE, or run the firmware step that produces board.toml [firmware] fd'
        return 0
    fi
    local fd="$FD_PATH_IN"

    # (2) host and tools.  bootimg.py:24 compiles the shim with clang,
    # llvm-objcopy and llvm-nm; bootimg.py:46 patches the tree with fdtput and
    # fdtget.
    local -a need=('clang' 'llvm-objcopy' 'llvm-nm' 'fdtput' 'fdtget' 'python3')
    log_keg
    apple_step_gate "$name" "${need[@]}" || return 0

    # (3) run.  The output is out/<device>/boot/boot.img unless -o says
    # otherwise (bootimg.py:85).
    local out
    out="$(work_dir)/boot/boot.img"
    if ! run_driver "$name" 'bootimg' --uefi "$UEFI_DIR" --fd "$fd" --dtb "$DTB_PATH" \
            -o "$out"; then
        ledger_add "$name" 'failed' "unixnu bootimg failed; see $OUT_DIR/${name}.driver.log"
        return 1
    fi

    # (4) bootimg.build() writes boot.json next to the image with the sha256 of
    # every part (bootimg.py:110-112); the image itself is the artifact.
    record_artifact "$out" 'firmware' 'aarch64'
    ledger_add "$name" 'ran' "unixnu bootimg; $(dirname -- "$out")/boot.json records the per-part hashes"
    return 0
}

# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
main() {
    step "preflight"
    log "run_id:    $RUN_ID"
    log "stage:     $STAGE"
    log "experiment:$EXPERIMENT"
    log "target:    $TARGET"
    log "lock:      $LOCK_PATH"
    log "out:       $OUT_DIR"
    # Which plan this run will follow, and why: build-payload is the one opt-in
    # stage, and a reader of the log must be able to tell "the payload was not
    # asked for" from "the payload step refused".
    if (( BUILD_PAYLOAD )); then
        log "payload:   requested ($PAYLOAD_REQUESTED); build-payload is planned"
        # build-payload loads DarwinBoot.efi as a driver and refuses without it,
        # and build-bootloader is milestone-gated at n>=3 (plan_steps).  So a
        # stage below 3 that asks for a payload is a GUARANTEED not_run, and it is
        # a silent one: the stage records its reason two stages later, after the
        # kernel has been built.  Measured on run 40186682998 -- --stage M2 with
        # BUILD_PAYLOAD=1 produced exactly that, and the owner root chain then
        # died in build-storage-abi.py for want of the payload.img it boots.  The
        # earlier runs that reached the driver used M4, which is where the
        # bootloader is planned.  Named here so the reader sees it before the
        # work is spent rather than in the ledger after.
        if (( STAGE_NUMBER < 3 )); then
            log "payload:   WARNING stage $STAGE does not plan build-bootloader (plan_steps gates it at n>=3), so build-payload will record not_run for a missing DarwinBoot.efi; pass a stage of 3 or more to get a payload volume"
        fi
    else
        log 'payload:   not requested (no --payload, BUILD_PAYLOAD empty); no ESP volume will be built'
    fi
    if (( DRY_RUN )); then log 'mode:      dry-run (nothing written, nothing built)'; fi

    validate_lock
    # The frozen state is the lock's own, never a literal.  This line used to
    # read `frozen=true` unconditionally, so an unfrozen run's log claimed the
    # opposite of what its own manifest recorded -- the one place an operator
    # would look to find out which baseline was built.
    log "lock: frozen=$LOCK_FROZEN unixnu=$LOCK_UNIXNU_COMMIT device_repo=$LOCK_DEVICE_COMMIT"
    if (( LOCK_UNFROZEN )); then
        log 'lock: NOT FROZEN -- the pinned commits above are this run'"'"'s freeze candidates, recorded verbatim in artifact-manifest.json'
    fi
    log "lock: qemu accel=$LOCK_QEMU_ACCEL ipsw.sha256=${LOCK_IPSW_SHA256:-<empty>}"
    # The third pinned checkout, and what its absence costs.  Printed here
    # rather than only inside build-payload so a reader of the log sees before
    # the run whether the panic screen's font header has a source at all --
    # measured need: runs 40094234507 and 40096928333 reached the driver and
    # died in clang with "fatal error: 'Font.h' file not found" for want of it.
    if [[ -n "$UEFI_DIR" ]]; then
        log "uefi:     $UEFI_DIR (Mu-Silicium; the panic screen's Font.h comes from here)"
    else
        log 'uefi:     <none: no --uefi>. If board.toml [payload] panic_screen is set, build-payload will record failed: its font header has no source'
    fi

    require_tools
    log "tools: $TOOL_XCODEBUILD"
    log "tools: $TOOL_CLANG"
    log "tools: $TOOL_PYTHON"
    log "tools: $TOOL_GIT"

    # Parallel jobs for the driver (cli.py:19, config.py:86).  Counted with the
    # interpreter this script already requires, because nproc is not on macOS.
    if [[ -z "$JOBS" ]]; then
        JOBS="$("$PY" -c 'import os; print(os.cpu_count() or 4)' 2>/dev/null || printf '4')"
    fi
    if [[ ! "$JOBS" =~ ^[0-9]+$ ]] || (( JOBS < 1 )); then
        die 'config_invalid' "jobs must be a positive integer (got '$JOBS')." '{}' "$EXIT_USAGE"
    fi

    detect_sha

    prepare_output_dir
    if (( DRY_RUN == 0 )); then
        check_free_space
    fi

    # --- declared deliverables --------------------------------------------
    # Each --include is an input that must exist; a missing one is a failure,
    # never a silently empty manifest (PRD 7.4).
    local -a inc_paths=() inc_roles=() inc_archs=()
    local spec path role arch rest
    for spec in ${INCLUDES[@]+"${INCLUDES[@]}"}; do
        # '::' is the delimiter, not ':': a Windows drive letter ("C:/x") must
        # not be split into a path of "C" and a role of "/x".  Splitting with
        # IFS=':' cannot express that, so use parameter expansion instead.
        path="${spec%%::*}"
        rest="${spec#*::}"
        [[ "$rest" == "$spec" ]] && rest=''
        role="${rest%%::*}"
        arch="${rest#*::}"
        [[ "$arch" == "$rest" ]] && arch=''
        if [[ -z "$path" ]]; then
            die 'config_invalid' "--include needs a path." '{}' "$EXIT_USAGE"
        fi
        # Absolute means POSIX "/..." or a Windows drive "C:/" / "C:\".
        if [[ "$path" != /* && ! "$path" =~ ^[A-Za-z]:[/\\] ]]; then
            path="$REPO_ROOT/$path"
        fi
        if [[ ! -f "$path" ]]; then
            die 'artifact_missing' "declared artifact is missing: $path" \
                "{\"include\":\"$(json_escape "$spec")\"}" "$EXIT_FAILURE"
        fi
        if [[ -z "$role" ]]; then
            case "$path" in
                *kernelcache*|*kernel*) role='kernel' ;;
                *devicetree*|*.dtb|*.dts) role='devicetree' ;;
                *boot*|*loader*|*iboot*)  role='bootloader' ;;
                *)                        role='auxiliary' ;;
            esac
        fi
        [[ -n "$arch" ]] || arch='aarch64'
        inc_paths+=("$path"); inc_roles+=("$role"); inc_archs+=("$arch")
    done

    # --- plan --------------------------------------------------------------
    step "plan"
    # mapfile is bash 4+; macOS ships /bin/bash 3.2, so read the plan in a loop.
    local -a steps=()
    local s
    while IFS= read -r s; do
        [[ -n "$s" ]] && steps+=("$s")
    done < <(plan_steps "$STAGE_NUMBER")
    local idx
    for (( idx = 0; idx < ${#steps[@]}; idx++ )); do
        printf '  %s\n' "${steps[$idx]}"
    done
    ledger_add 'preflight' 'ran' 'validated inputs, lock, tools and space'

    if (( DRY_RUN )); then
        for (( idx = 0; idx < ${#steps[@]}; idx++ )); do
            [[ "${steps[$idx]}" == 'preflight' ]] && continue
            ledger_add "${steps[$idx]}" 'not_run' 'dry-run'
        done
        printf '\n'
        log "dry-run complete; run id would be $RUN_ID"
        printf '{\n  "run_id": "%s",\n  "stage": "%s",\n  "target": "%s",\n  "dry_run": true,\n  "planned_steps": [' \
            "$(json_escape "$RUN_ID")" "$(json_escape "$STAGE")" "$(json_escape "$TARGET")"
        local first=1
        for (( idx = 0; idx < ${#steps[@]}; idx++ )); do
            (( first )) || printf ', '
            first=0
            printf '"%s"' "$(json_escape "${steps[$idx]}")"
        done
        printf ']\n}\n'
        exit "$EXIT_OK"
    fi

    # --- run the plan ------------------------------------------------------
    local sources_present=0
    local stage_failed=0
    for (( idx = 0; idx < ${#steps[@]}; idx++ )); do
        s="${steps[$idx]}"
        case "$s" in
            preflight)
                # already recorded
                ;;
            prepare-sources)
                step "prepare-sources"
                # No network access, ever.  The pinned checkouts are verified
                # locally; an absent one is a missing input unless the caller
                # explicitly opts out.
                local checkout
                for checkout in "$UNIXNU_DIR" "$DEVICE_DIR"; do
                    if [[ -d "$checkout/.git" ]]; then
                        log "source present: $checkout"
                        sources_present=1
                    else
                        log "source absent:  $checkout"
                    fi
                done
                if (( sources_present == 0 )) && (( SKIP_SOURCES == 0 )); then
                    ledger_add "$s" 'not_run' 'pinned source checkout absent'
                    emit_error 'artifact_missing' \
                        'no pinned source checkout found; nothing was fetched (no network access by policy).' \
                        "{\"expected\":[\"$(json_escape "$UNIXNU_DIR")\",\"$(json_escape "$DEVICE_DIR")\"],\"hint\":\"pass --unixnu/--device to point at the checkouts, or --skip-sources to validate the contract only\"}"
                    write_outputs 0 0
                    exit "$EXIT_FAILURE"
                fi
                if (( sources_present == 0 )); then
                    log 'note: --skip-sources given; build steps will stay not_run.'
                    ledger_add "$s" 'not_run' 'pinned source checkout absent (--skip-sources)'
                else
                    # The driver fetches whatever its feeds root is missing and
                    # initialises module submodules (cli.py:79-86), so prove
                    # both are already on disk at the pinned commit first.
                    resolve_board
                    local -a missing=()
                    local line
                    while IFS="$(printf '\t')" read -r kind name; do
                        missing+=("$kind:$name")
                    done < <(offline_missing)
                    if (( ${#missing[@]} > 0 )); then
                        log "sources the driver would have to fetch: ${missing[*]}"
                        if (( SKIP_SOURCES == 0 )); then
                            ledger_add "$s" 'not_run' \
                                "pinned sources are not on disk at the locked commits: ${missing[*]}"
                            emit_error 'artifact_missing' \
                                "pinned sources are missing and this script performs no network access, so the upstream driver cannot be allowed to fetch them: ${missing[*]}" \
                                "{\"missing\":$(json_string_array ${missing[@]+"${missing[@]}"}),\"hint\":\"restore the pinned sources, or pass --skip-sources to validate the contract only\"}"
                            write_outputs 0 0
                            exit "$EXIT_FAILURE"
                        fi
                        log 'note: --skip-sources given; build steps will stay not_run.'
                        ledger_add "$s" 'not_run' \
                            "pinned sources absent, the driver would fetch them and this script performs no network access (--skip-sources): ${missing[*]}"
                        SOURCES_INCOMPLETE=1
                    else
                        ledger_add "$s" 'ran' \
                            'pinned repositories, module submodules and feed clones verified locally at the locked commits; nothing was fetched'
                    fi
                fi
                ;;
            build-os-root)
                step "$s"
                if (( SOURCES_INCOMPLETE )); then
                    ledger_add "$s" 'not_run' 'pinned sources absent (--skip-sources); the driver would have to fetch them'
                elif step_build_os_root; then
                    :
                else
                    stage_failed=1
                fi
                ;;
            build-kernel)
                step "$s"
                if (( SOURCES_INCOMPLETE )); then
                    ledger_add "$s" 'not_run' 'pinned sources absent (--skip-sources); the driver would have to fetch them'
                elif step_build_kernel; then
                    :
                else
                    stage_failed=1
                fi
                ;;
            build-bootloader)
                step "$s"
                if (( SOURCES_INCOMPLETE )); then
                    ledger_add "$s" 'not_run' 'pinned sources absent (--skip-sources); the driver would have to fetch them'
                elif step_build_bootloader; then
                    :
                else
                    stage_failed=1
                fi
                ;;
            build-payload)
                step "$s"
                if (( SOURCES_INCOMPLETE )); then
                    ledger_add "$s" 'not_run' 'pinned sources absent (--skip-sources); the driver would have to fetch them'
                elif step_build_payload; then
                    :
                else
                    stage_failed=1
                fi
                ;;
            build-devicetree)
                step "$s"
                if (( SOURCES_INCOMPLETE )); then
                    ledger_add "$s" 'not_run' 'pinned sources absent (--skip-sources); the driver would have to fetch them'
                elif step_build_devicetree; then
                    :
                else
                    stage_failed=1
                fi
                ;;
            assemble-image)
                step "$s"
                if (( SOURCES_INCOMPLETE )); then
                    ledger_add "$s" 'not_run' 'pinned sources absent (--skip-sources); the driver would have to fetch them'
                elif step_assemble_image; then
                    :
                else
                    stage_failed=1
                fi
                ;;
            verify-artifacts)
                step 'verify-artifacts'
                if (( ${#inc_paths[@]} == 0 )) && (( ${#BUILT_RECORDS[@]} == 0 )); then
                    log 'no declared deliverables and nothing built; the manifest will'
                    log 'list only the metadata files this script itself writes.'
                fi
                # Re-hash every artifact the manifest is about to carry, so a
                # hash a stage recorded is checked again before it is published.
                # A mismatch here is a verification failure, not a warning.
                local i again
                for (( i = 0; i < ${#BUILT_PATHS[@]}; i++ )); do
                    again="$(sha256_of "${BUILT_PATHS[$i]}")"
                    if [[ "$again" != "${BUILT_SHAS[$i]}" ]]; then
                        die 'verification_failed' \
                            "${BUILT_PATHS[$i]} changed between the stage that built it and verification." \
                            "{\"path\":\"$(json_escape "${BUILT_PATHS[$i]}")\",\"recorded\":\"${BUILT_SHAS[$i]}\",\"now\":\"$again\"}" \
                            "$EXIT_FAILURE"
                    fi
                done
                ledger_add "$s" 'ran' \
                    "every artifact the manifest carries was re-hashed (${#inc_paths[@]} declared, ${#BUILT_RECORDS[@]} built)"
                ;;
            write-manifest)
                step 'write-manifest'
                ledger_add "$s" 'ran' 'artifact-manifest.json written'
                ;;
            material-manifest)
                step 'material-manifest'
                # Not gated on SOURCES_INCOMPLETE the way the build stages are:
                # this stage reads the board and the tree, never a pinned source
                # that would have to be fetched.  A stage that could not run
                # records that itself, with the stage that should have produced
                # each missing input named.
                if step_material_manifest; then
                    :
                else
                    stage_failed=1
                fi
                ;;
        esac
        # A stage that failed stops the plan: the next stage's inputs come out
        # of it.  The outputs are still written, so the evidence of what did and
        # did not happen is on disk.
        if (( stage_failed )); then
            log "stage $s failed; the remaining stages are not_run."
            local rest
            for (( rest = idx + 1; rest < ${#steps[@]}; rest++ )); do
                ledger_add "${steps[$rest]}" 'not_run' "an earlier stage failed: $s"
            done
            break
        fi
    done

    # "$sources_present" and not a literal 1: with --skip-sources the ledger
    # says the sources were absent, so the report must agree with it.
    write_outputs "$sources_present" "${#inc_paths[@]}"

    step "summary"
    log "run_id:  $RUN_ID"
    log "out:     $OUT_DIR"
    log "log:     $LOG_PATH"
    log "report:  $REPORT_PATH"
    log "manifest:$MANIFEST_PATH"
    log "stages:  $(ledger_summary)"
    if (( stage_failed )); then
        log 'A stage FAILED.  Nothing here may be read as a build result.'
        exit "$EXIT_FAILURE"
    fi
    if ledger_has_not_run; then
        log 'NOTE: not every stage ran.  A stage that did not run is recorded'
        log '      not_run with its reason in build-report.json; missing evidence'
        log '      is unverified, never success (PRD 7.4).'
    fi

    exit "$EXIT_OK"
}

# write_outputs SOURCES_OK DECLARED_COUNT
# Writes build.log content already produced by log(), build-report.json and
# artifact-manifest.json in the canonical form of unipad.models.write_json.
write_outputs() {
    local sources_ok="$1" declared_count="$2"
    local i sha size leaf

    # --- artifact entries --------------------------------------------------
    # Declared deliverables are hashed here, one record per file, so the
    # manifest writer only has to serialise them.  Artifacts the build stages
    # produced were hashed where they were produced (record_artifact) and are
    # appended after them, so one manifest carries both.
    local -a records=()
    for (( i = 0; i < ${#inc_paths[@]}; i++ )); do
        sha="$(sha256_of "${inc_paths[$i]}")"
        if [[ ! "$sha" =~ $SHA256_PATTERN ]]; then
            die 'verification_failed' \
                "could not compute the SHA-256 of ${inc_paths[$i]}." \
                "{\"path\":\"$(json_escape "${inc_paths[$i]}")\"}" "$EXIT_FAILURE"
        fi
        size="$(wc -c <"${inc_paths[$i]}" | tr -d ' ')"
        leaf="$(basename -- "${inc_paths[$i]}")"
        # The path is recorded the same way record_artifact records a built one:
        # relative to this run's output directory when it is inside it, and the
        # path as given otherwise.  Recording only the leaf -- which is what this
        # line did -- made two declared inputs with the same basename
        # indistinguishable and left a consumer with a path that locates nothing.
        records+=("${leaf}${FIELD_SEP}${sha}${FIELD_SEP}${size}${FIELD_SEP}${inc_roles[$i]}${FIELD_SEP}${inc_archs[$i]}${FIELD_SEP}$(shown_path "${inc_paths[$i]}")")
        log "artifact: $leaf sha256=$sha bytes=$size role=${inc_roles[$i]} arch=${inc_archs[$i]}"
    done
    local rec
    for rec in ${BUILT_RECORDS[@]+"${BUILT_RECORDS[@]}"}; do
        records+=("$rec")
    done

    # --- build-report.json -------------------------------------------------
    # Every escaped value goes through json_escape_var into a local first.  The
    # printing form costs a subshell per call and there are two dozen here; on a
    # host where a fork is ~0.85 s that dominated the run.
    local j_run_id j_stage j_experiment j_target j_generated j_driver j_device
    local j_driver_out j_lock_path j_lock_unixnu j_lock_device j_lock_accel
    local j_xcode j_clang j_python j_git j_qemu
    json_escape_var j_run_id      "$RUN_ID"
    json_escape_var j_stage       "$STAGE"
    json_escape_var j_experiment  "$EXPERIMENT"
    json_escape_var j_target      "$TARGET"
    json_escape_var j_driver      "$DRIVER"
    json_escape_var j_device      "$DEVICE_DIR"
    json_escape_var j_driver_out  "$UNIXNU_OUT"
    json_escape_var j_lock_path   "$LOCK_PATH"
    json_escape_var j_lock_unixnu "$LOCK_UNIXNU_COMMIT"
    json_escape_var j_lock_device "$LOCK_DEVICE_COMMIT"
    json_escape_var j_lock_accel  "$LOCK_QEMU_ACCEL"
    json_escape_var j_xcode       "$TOOL_XCODEBUILD"
    json_escape_var j_clang       "$TOOL_CLANG"
    json_escape_var j_python      "$TOOL_PYTHON"
    json_escape_var j_git         "$TOOL_GIT"
    json_escape_var j_qemu        "$TOOL_QEMU"
    stamp_var j_generated
    {
        printf '{\n'
        printf '  "command": "build-macos",\n'
        printf '  "run_id": "%s",\n'        "$j_run_id"
        printf '  "stage": "%s",\n'         "$j_stage"
        printf '  "experiment": "%s",\n'    "$j_experiment"
        printf '  "target": "%s",\n'        "$j_target"
        printf '  "generated_at": "%s",\n'  "$j_generated"
        printf '  "build_mode": "upstream-driver",\n'
        printf '  "driver": "%s",\n'        "$j_driver"
        printf '  "device_repo": "%s",\n'   "$j_device"
        printf '  "driver_out": "%s",\n'    "$j_driver_out"
        printf '  "network_access": "none",\n'
        printf '  "sources_incomplete": %s,\n' \
            "$([[ "$SOURCES_INCOMPLETE" == '1' ]] && printf 'true' || printf 'false')"
        printf '  "lock": {\n'
        printf '    "path": "%s",\n'        "$j_lock_path"
        printf '    "frozen": %s,\n'        "$([[ "$LOCK_FROZEN" == 'true' ]] && printf 'true' || printf 'false')"
        # A run against an unfrozen lock says so in machine-readable form, so no
        # downstream consumer can read `frozen: false` as a frozen baseline by
        # ignoring it.  The commits below are what was built, whatever the flag
        # says, and they are the freeze candidates for the next lock.
        #
        # The whole conditional goes inside ONE command substitution.  Spelled
        # `$(( LOCK_UNFROZEN )) && printf ...` instead, the arithmetic expansion
        # is evaluated inside the double quotes and the rest of the line is
        # literal text: the file then carries `"unfrozen_build": 0 && printf
        # 'true' || printf 'false',` and is not JSON at all.  Measured.
        printf '    "unfrozen_build": %s,\n' \
            "$([[ "$LOCK_UNFROZEN" == '1' ]] && printf 'true' || printf 'false')"
        printf '    "unixnu_commit": "%s",\n'    "$j_lock_unixnu"
        printf '    "device_repo_commit": "%s",\n' "$j_lock_device"
        printf '    "qemu_accel": "%s"\n'        "$j_lock_accel"
        printf '  },\n'
        printf '  "toolchain": {\n'
        printf '    "xcodebuild": "%s",\n'  "$j_xcode"
        printf '    "clang": "%s",\n'       "$j_clang"
        printf '    "python3": "%s",\n'     "$j_python"
        printf '    "git": "%s",\n'         "$j_git"
        # qemu-system-aarch64 IS a build input, of exactly one sub-step:
        # make-qemu-adt.py:93-101 dumps the machine's own device tree through it.
        # The value is what preflight found, so the report distinguishes "it was
        # already there" from "the sub-step installed it" from "there was none".
        printf '    "qemu": "%s"\n'         "$j_qemu"
        printf '  },\n'
        printf '  "steps": %s,\n' "$(ledger_json)"
        printf '  "declared_artifacts": %s,\n' "$declared_count"
        printf '  "built_artifacts": %s,\n'   "${#BUILT_RECORDS[@]}"
        printf '  "sources_present": %s,\n' "$([[ "$sources_ok" == '1' ]] && printf 'true' || printf 'false')"
        printf '  "evidence_note": "steps with status not_run or failed produced nothing; missing evidence is unverified, not success (PRD 7.4).",\n'
        printf '  "config_divergence": "%s"\n' "$(json_escape "$CONFIG_DIVERGENCE")"
        printf '}\n'
    } >"$REPORT_PATH"
    assert_json_file "$REPORT_PATH" "build report" 'build_report_invalid'

    # --- stage-result.json -------------------------------------------------
    # One machine-readable stage result, as PRD 8.1 "报告" requires.  ok is
    # derived from the ledger, never asserted: a stage in which anything is
    # not_run or failed cannot report success.
    local ok='false' status='incomplete'
    if ! ledger_has_not_run; then
        ok='true'
        status='complete'
    fi
    stamp_var j_generated
    {
        printf '{\n'
        printf '  "stage": "%s",\n'      "$j_stage"
        printf '  "run_id": "%s",\n'     "$j_run_id"
        printf '  "status": "%s",\n'     "$status"
        printf '  "ok": %s,\n'           "$ok"
        printf '  "generated_at": "%s",\n' "$j_generated"
        printf '  "steps": %s,\n' "$(ledger_json)"
        printf '  "step_summary": "%s",\n' "$(ledger_summary)"
        printf '  "not_run_reasons": %s,\n' "$(not_run_reasons_json)"
        printf '  "note": "A stage in which anything is not_run or failed never reports success. Real Apple-tool work is UNVERIFIED off macOS (PRD 7.4)."\n'
        printf '}\n'
    } >"$STAGE_RESULT_PATH"
    assert_json_file "$STAGE_RESULT_PATH" "stage result" 'stage_result_invalid'

    # --- artifact-manifest.json -------------------------------------------
    # Written through Python so the bytes match unipad.models.write_json
    # (ensure_ascii=False, sort_keys=True, indent=2, trailing newline) exactly.
    # The records go through a temp file rather than a pipe: the manifest
    # writer's heredoc would otherwise replace stdin and silently drop every
    # record, producing a valid manifest with an empty artifacts list.
    local records_file
    records_file="$(mktemp 2>/dev/null || printf '%s/.records.%s.tmp' "$OUT_DIR" "$$")"
    printf '%s\n' ${records[@]+"${records[@]}"} >"$records_file"
    write_manifest "$records_file"
    rm -f -- "$records_file"
    if [[ ! -s "$MANIFEST_PATH" ]]; then
        die 'evidence_incomplete' "artifact manifest was not written: $MANIFEST_PATH" \
            "{\"manifest\":\"$(json_escape "$MANIFEST_PATH")\"}" "$EXIT_FAILURE"
    fi
    assert_json_file "$MANIFEST_PATH" "artifact manifest" 'artifact_manifest_invalid'
}

# write_manifest RECORDS_FILE -- write MANIFEST_PATH from one-record-per-line
# TSV (fields separated by US, 0x1f):
#   name <US> sha256 <US> size_bytes <US> role <US> arch <US> path
# The shape is unipad.models.ArtifactManifest exactly: run_id, artifacts[],
# target, unixnu_commit, device_repo_commit, toolchain.
write_manifest() {
    local records_file="$1"
    [[ -n "$PY" ]] || die 'blocked' 'no Python interpreter for the manifest writer.' \
        '{}' "$EXIT_BLOCKED"
    [[ -f "$records_file" ]] || die 'evidence_incomplete' \
        "artifact records file is missing: $records_file" '{}' "$EXIT_FAILURE"
    "$PY" - "$MANIFEST_PATH" "$RUN_ID" "$TARGET" \
        "$LOCK_UNIXNU_COMMIT" "$LOCK_DEVICE_COMMIT" "$records_file" \
        "$TOOL_XCODEBUILD" "$TOOL_CLANG" "$TOOL_PYTHON" "$TOOL_GIT" <<'PYEOF'
import json
import sys

sep = "\037"
(manifest_path, run_id, target, unixnu_commit, device_repo_commit,
 records_file, xcodebuild, clang, python3, git) = sys.argv[1:11]

artifacts = []
with open(records_file, 'r', encoding='utf-8') as handle:
    for line in handle.read().split("\n"):
        line = line.rstrip("\r")
        if not line:
            continue
        name, sha256, size_bytes, role, arch, path = line.split(sep)
        artifacts.append({
            "name": name,
            "sha256": sha256,
            "size_bytes": int(size_bytes),
            "arch": arch if arch else None,
            "role": role if role else None,
            "path": path,
        })

manifest = {
    "run_id": run_id,
    "artifacts": artifacts,
    "target": target,
    "unixnu_commit": unixnu_commit,
    "device_repo_commit": device_repo_commit,
    "toolchain": {
        "xcodebuild": xcodebuild,
        "clang": clang,
        "python3": python3,
        "git": git,
    },
}

with open(manifest_path, "w", encoding="utf-8") as handle:
    handle.write(json.dumps(manifest, ensure_ascii=False, sort_keys=True, indent=2) + "\n")
PYEOF
}

main "$@"
