check_free_space() {
    local free_kb free_gb
    free_kb="$(df -Pk -- "$OUT_DIR" 2>/dev/null | awk 'NR==2 {print $4}')" || free_kb=''
    if [[ ! "$free_kb" =~ ^[0-9]+$ ]]; then
        log 'warning: free space on the output filesystem could not be determined.'
        return 0
    fi
    free_gb=$(( free_kb / 1024 / 1024 ))
    if (( free_gb < MIN_FREE_GB )); then
        die 'blocked' \
            "not enough free space on $OUT_DIR: ${free_gb} GiB free, ${MIN_FREE_GB} GiB required." \
            "{\"free_gb\":$free_gb,\"required_gb\":$MIN_FREE_GB,\"out\":\"$(json_escape "$OUT_DIR")\"}" \
            "$EXIT_BLOCKED"
    fi
    log "free space: ${free_gb} GiB (required ${MIN_FREE_GB} GiB)"
}

# ---------------------------------------------------------------------------
# step ledger
# ---------------------------------------------------------------------------
# Each entry: name|status|reason   (status: ran | not_run | skipped | failed)
LEDGER=()

# Artifacts the build stages actually produced, in the same record shape the
# manifest writer consumes (see write_manifest).  A stage that produced nothing
# appends nothing, so the manifest can never carry a hash of a file that is not
# there.
BUILT_RECORDS=()
BUILT_PATHS=()
BUILT_SHAS=()

# Set when the pinned sources are absent and --skip-sources was given: the
# stages then stay not_run instead of letting the driver fetch on our behalf.
SOURCES_INCOMPLETE=0

ledger_add() { LEDGER+=("$1|$2|$3"); }

ledger_json() {
    local first=1 entry name status reason
    local j_name j_status j_reason
    printf '['
    for entry in ${LEDGER[@]+"${LEDGER[@]}"}; do
        name="${entry%%|*}"
        status="${entry#*|}"; status="${status%%|*}"
        reason="${entry##*|}"
        (( first )) || printf ','
        first=0
        json_escape_var j_name   "$name"
        json_escape_var j_status "$status"
        json_escape_var j_reason "$reason"
        printf '{"name":"%s","status":"%s","reason":"%s"}' \
            "$j_name" "$j_status" "$j_reason"
    done
    printf ']'
}

# ledger_has_not_run -- true when any entry did not run or failed.  A stage
# result may only report success when this is false.
ledger_has_not_run() {
    local entry status
    for entry in ${LEDGER[@]+"${LEDGER[@]}"}; do
        status="${entry#*|}"; status="${status%%|*}"
        case "$status" in
            not_run|failed) return 0 ;;
        esac
    done
    return 1
}

# ledger_summary -- "ran=N not_run=N failed=N skipped=N", for the console.
ledger_summary() {
    local entry status ran=0 not_run=0 failed=0 skipped=0
    for entry in ${LEDGER[@]+"${LEDGER[@]}"}; do
        status="${entry#*|}"; status="${status%%|*}"
        case "$status" in
            ran)     ran=$(( ran + 1 )) ;;
            not_run) not_run=$(( not_run + 1 )) ;;
            failed)  failed=$(( failed + 1 )) ;;
            skipped) skipped=$(( skipped + 1 )) ;;
        esac
    done
    printf 'ran=%d not_run=%d failed=%d skipped=%d' "$ran" "$not_run" "$failed" "$skipped"
}

# not_run_reasons_json -- the distinct "name: reason" of every entry that did
# not run or failed, as a JSON array.  Derived from the ledger rather than
# hardcoded, so a new refusal shows up here without anyone remembering to.
not_run_reasons_json() {
    local first=1 entry name status reason seen=''
    local j_name j_reason
    printf '['
    for entry in ${LEDGER[@]+"${LEDGER[@]}"}; do
        name="${entry%%|*}"
        status="${entry#*|}"; status="${status%%|*}"
        reason="${entry##*|}"
        case "$status" in
            not_run|failed) ;;
            *) continue ;;
        esac
        case "$seen" in
            *"|$name|$reason|"*) continue ;;
        esac
        seen+="|$name|$reason|"
        (( first )) || printf ','
        first=0
        json_escape_var j_name   "$name"
        json_escape_var j_reason "$reason"
        printf '"%s: %s"' "$j_name" "$j_reason"
    done
    printf ']'
}

# ---------------------------------------------------------------------------
# the material manifest
# ---------------------------------------------------------------------------
# material_manifest_path -- where this run's manifest is written.
#
# Under OUT_DIR and not under the tree, for the same reason the other evidence
# files are: the staging step scans BUILD_OUTPUT_DIR, and a manifest inside the
# build tree would be found twice or not at all depending on where the tree is
# assembled this run.
#
# Inside the delivery directory and not beside the other run evidence on
# purpose.  The manifest names the Data seed -- its digest, its measured size
# and the volume UUID the kernel was built with -- so it is the index of
# Apple-derived material even though it is not itself Apple material, and it has
# to travel the channel the material travels.  Keeping every file this stage
# writes in ONE directory is what makes that enforceable with one staging
# pattern ("private/*") instead of a list of names that can drift; the verdict
# is still public, because build-report.json's ledger records whether the stage
# ran, failed or did not run and why, without the material's identity.
material_manifest_path() { printf '%s' "$(material_delivery_dir)/material-manifest.json"; }

# material_delivery_dir -- the flat directory a delivery is staged into.
#
# The manifest records LEAF names, because the same manifest has to be readable
# on a macOS runner and on a Windows host that downloaded the material into one
# place.  A flat directory is what that means, and it is the layout the
# workflow's boot-inputs bundle already uses.
material_delivery_dir() { printf '%s' "$OUT_DIR/private"; }

# openssl_keg -- the OpenSSL 3 keg this host has, or nothing.
#
# macOS ships /usr/bin/openssl, and that one is LibreSSL, whose `enc` has no GCM:
# `openssl enc -aes-256-gcm` fails on it.  The material delivery encrypts with
# exactly that cipher, so it must use the keg the workflow installs (its "Install
# OpenSSL 3" step, which also exports OPENSSL_PREFIX) rather than whatever bare
# `openssl` resolves to.  Measured on run 40392771419: the delivery's encryption
# failed with no line in the step log at all, because the script called the
# system LibreSSL and sent its stderr into a file under private/, which is never
# uploaded.  The owner root chain resolves the same keg for its host verifier;
# this is that resolution, named once instead of spelled twice.
openssl_keg() {
    local candidate
    for candidate in /opt/homebrew/opt/openssl@3 /usr/local/opt/openssl@3; do
        if [[ -d "$candidate" ]]; then printf '%s' "$candidate"; return 0; fi
    done
    return 0
}

# openssl_bin -- the openssl to encrypt with: the keg's, or PATH's as a fallback.
#
# The fallback is deliberate rather than lazy: on a host with no keg the delivery
# cannot be encrypted at all, and the caller's error message has to say which
# binary was tried so the operator can see it was the system one.
openssl_bin() {
    local keg; keg="$(openssl_keg)"
    if [[ -n "$keg" && -x "$keg/bin/openssl" ]]; then
        printf '%s' "$keg/bin/openssl"
    else
        printf 'openssl'
    fi
}

# material_kernelcache -- the donor kernelcache the prelink step used.
#
# unipad.host.ipsw publishes it as <cache>/<board.build>/kernelcache.decompressed,
# and the workflow passes --kernelcache-cache build-output/unixnu-out/ipsw
# (build-macos.yml), which is also the driver's own IPSW cache because the
# driver's --out is $UNIXNU_OUT.  The plain $OUT_DIR/ipsw spelling is searched
# too, because --kernelcache-cache is a flag and a caller may point it
# elsewhere; globbing the build directory rather than naming the build is the
# driver's own habit (ipsw.py:1355) and avoids reading board.toml [ipsw] build a
# second time just to build a path.
material_kernelcache() {
    local candidate
    for candidate in "$UNIXNU_OUT"/ipsw/*/kernelcache.decompressed \
                     "$OUT_DIR"/ipsw/*/kernelcache.decompressed; do
        [[ -f "$candidate" ]] && { printf '%s' "$candidate"; return 0; }
    done
    return 0
}

# material-manifest -- record which build produced what, and refuse if it does
#   not hold together.
#
# WHY THIS STEP EXISTS.  Until now nothing recorded which build produced which
# piece of a boot's material, and nothing checked that the pieces still belong
# together.  The consequence was measured on 2026-10-26 (implementation-plan
# fact 81): the owner-data-1g.dbr on this host's ESP is a 36,960-byte
# hand-written stub whose container superblock is correct in every field a
# structural check reads -- NXSB, 4096, 262144 blocks -- and whose nx_uuid is
# 00 01 02 ... 0f.  It was wired up and booted, and only the guest's own
# console said it was not an APFS container.  The real runner-built seed is
# 1,245,328 bytes.
#
# So the manifest binds five things a plausible-looking file cannot satisfy by
# accident: one build id for every artifact; a known producer for every
# artifact; the hash and the size, recomputed from the bytes; the Data volume
# UUID equal in the seed and in the kernel; and the pinned identity of the
# donor kernelcache and the ADT's root-match UUID, both read out of board.toml
# rather than restated here.
#
# The step verifies before it publishes, and a verification failure is a failed
# stage rather than a warning: a manifest that does not verify is exactly the
# artifact that must not be delivered.
step_material_manifest() {
    local name='material-manifest'

    # (1) the inputs.  Each one is named with the stage that produces it, so a
    #     not_run says which earlier stage did not run rather than only that
    #     something is missing.
    #
    #     $(tree_dir) and NOT $(work_dir) for the header: unixnu/config.py:80-82
    #     gives the driver TWO output roots, and the board's [board] name is
    #     'qemu' while its defconfig is 'qemu_root_defconfig', so on this board
    #     the pair is build-output/unixnu-out/qemu (kernel/, payload/, .config)
    #     and build-output/unixnu-out/qemu/tree (build/, scripts/).  kernel.py:100
    #     runs build-xnu-4k-baseline.sh with cwd=ctx.tree and that script derives
    #     ROOT from BASH_SOURCE (line 5), so OWNER_DATA_HEADER (line 394) lands in
    #     the tree's build/.  Measured on run 40339678974: the stage looked under
    #     unixnu-out/qemu/build/ and recorded not_run on BOTH of that run's build
    #     passes -- the second of which had just built a real 1 GiB Data seed and
    #     a kernel compiled with its UUID -- while the kernel log from the same
    #     seconds shows the script that writes it running out of
    #     unixnu-out/qemu/tree/.  One missing segment, and it cost the run its
    #     whole encrypted delivery.  The workflow's own chain step draws the same
    #     split (build-macos.yml:1636-1638: tree="$(ls -d "$OUT_ROOT"/*/tree)";
    #     work="$(dirname "$tree")").
    local header seed kernelcache
    header="$(tree_dir)/build/xnu/owner-data-volume.h"
    seed="$(os_root_seed_json)"; seed="${seed%/*}/owner-data-1g.dbr"
    kernelcache="$(material_kernelcache)"
    if [[ ! -f "$header" ]]; then
        ledger_add "$name" 'not_run' \
            "the kernel's owner-data-volume.h is not on disk ($(shown_path "$header")): build-kernel did not run, and without it no Data volume UUID can be bound to the kernel that was built"
        return 0
    fi
    if [[ ! -f "$seed" ]]; then
        ledger_add "$name" 'not_run' \
            "the owner root chain's packed Data seed is not on disk ($(shown_path "$seed")): build-os-root did not produce it, and a manifest without the seed cannot be verified against anything"
        return 0
    fi
    if [[ ! -f "$kernelcache" ]]; then
        ledger_add "$name" 'not_run' \
            "the donor kernelcache is in neither $(shown_path "$UNIXNU_OUT/ipsw") nor $(shown_path "$OUT_DIR/ipsw"): the acquisition step publishes it with --kernelcache-cache, and without it board.toml [kernel.prelink] kernelcache_sha256 cannot be checked"
        return 0
    fi
    local board="$DEVICE_DIR/board.toml"
    if [[ ! -f "$board" ]]; then
        ledger_add "$name" 'not_run' "board.toml is not at $(shown_path "$board")"
        return 0
    fi

    # Every input is present, so the delivery directory exists from here on.  It
    # is made before anything is written into it rather than at the point of
    # use, so a stage that fails halfway leaves a directory whose contents are
    # exactly the files that were produced -- and so the collect log below has
    # somewhere to be.
    local delivery manifest
    delivery="$(material_delivery_dir)"
    manifest="$(material_manifest_path)"
    mkdir -p "$delivery"

    # (2) collect.  The module hashes every file itself, so the digests in the
    #     manifest come from the same bytes the verification below will read.
    #     Both logs land in the delivery directory, beside the manifest they
    #     describe, because both print it: the collect log carries the digests
    #     and the volume UUID, which is the material's identity and not the
    #     build's.
    log "+ $PY -m unipad.host.material_manifest --collect (manifest $(shown_path "$manifest"))"
    if ! run_unipad -m unipad.host.material_manifest --collect \
            --tree "$(work_dir)" \
            --device "$DEVICE_DIR" \
            --esp "$OUT_DIR/payload-esp" \
            --kernelcache "$kernelcache" \
            --volumes "$DEVICE_DIR/.cache/firmware/target-volumes" \
            --board "$board" \
            --build-id "$RUN_ID" \
            --board-name "$BOARD_NAME" \
            --manifest "$manifest" \
            --device-commit "${LOCK_DEVICE_COMMIT:-}" \
            --unixnu-commit "${LOCK_UNIXNU_COMMIT:-}" \
            2>&1 | tee "$delivery/${name}.collect.log"; then
        ledger_add "$name" 'failed' \
            "the material could not be manifested; see $(shown_path "$delivery/${name}.collect.log")"
        return 1
    fi

    # (3) stage the flat delivery, then verify against the staged copy.
    #
    #     Verified against the delivery and not against the build tree on
    #     purpose: a manifest that is only true of the tree it was collected
    #     from is not a manifest of what was delivered, and the two differ by
    #     exactly the files that get left behind.
    local role path leaf
    # The roles and their leaf names, read out of the manifest rather than out of
    # a list here.  Written to a FILE rather than fed through a process
    # substitution, and that is not style: `done < <(cmd <<'PY' ... PY)` is the
    # only construct of its kind in this 4,000-line script -- the ten other
    # `done < <(...)` all call a shell function -- and macOS ships bash 3.2,
    # which refuses it.  Measured on run 40386064322, the first run in this
    # repository's history to reach this line at all, which died with
    #     bad substitution: no closing `)' in <(run_unipad - "$manifest" <<'PY'
    # after collecting a complete manifest.  A construct that has never run is a
    # construct nobody has measured, and this one is older than every fix in
    # implementation-plan facts 89 through 93: the stage always refused before
    # it got here, so the shell half was never executed even once.
    local roles_list stage_failed=0
    roles_list="$(mktemp 2>/dev/null || printf '%s/material-roles.%s.tmp' "$OUT_DIR" "$$")"
    if ! run_unipad - "$manifest" > "$roles_list" <<'PY'
import json, sys
manifest = json.load(open(sys.argv[1], encoding="utf-8"))
for role, entry in sorted(manifest["artifacts"].items()):
    # A role recorded without bytes (the two multi-GB members PRD 12 deletes) has
    # nothing to copy; its identity is the board's pin, checked in step (4).
    if entry.get("bytes"):
        print(role + "\t" + entry["path"])
PY
    then
        rm -f "$roles_list"
        ledger_add "$name" 'failed' \
            "the manifest's own roles could not be read back, so nothing can be staged into the delivery"
        return 1
    fi
    while IFS="$(printf '\t')" read -r role leaf; do
        [[ -n "$leaf" ]] || continue
        # Where this role's file is, named per role rather than searched for by
        # leaf name.  The search this replaces looked for "$root/$leaf" across
        # six roots and could not find three of the eight roles that carry
        # bytes: the kernel is under kernel/, the device tree under
        # EFI/UniXNU/Payloads/, and the trust bundle under
        # build/original-static-system-trust/ -- none of which is a root, so
        # "$root/$leaf" is a path no build writes.  Its last candidate was
        # "$kernelcache" unconditionally, so a role it could not find was
        # silently handed the donor Apple kernelcache under its own name, and
        # the verify below then refused it as a hash mismatch on the wrong file.
        # Measured on run 40369137221, whose boot inputs list names all three
        # real paths; the two-root split the old comment cited is the same one
        # the header check in (1) draws, but a root is not a directory.
        #
        # The order matches BuildTree.devicetree_candidates: the payload's tree
        # is the one the guest boots, and the devicetree stage's is what exists
        # on a pass where build-payload produced none.
        case "$role" in
            kernel)
                path="$(work_dir)/kernel/kernel.macho" ;;
            devicetree)
                path="${PAYLOAD_ADT_PATH:-}"
                [[ -n "$path" ]] || path="$(work_dir)/kernel/kernel.macho.adt" ;;
            trust_cache)
                path="$(tree_dir)/build/original-static-system-trust/original-static-system.bundle" ;;
            data_seed)
                path="$seed" ;;
            boot_config)
                path="$OUT_DIR/payload-esp/EFI/UniXNU/unixnu.toml" ;;
            kernelcache)
                path="$kernelcache" ;;
            *)
                # A role with bytes and no place to be is a role this stage
                # cannot stage; the verify below refuses the delivery rather
                # than a copy of something else standing in for it.
                path='' ;;
        esac
        # Absent is a refusal, not a skip: a delivery that is missing a file the
        # build really did produce is exactly what the verify in (3) exists to
        # catch, and it catches it with the role named only if nothing was
        # copied under that leaf.
        if [[ -z "$path" ]]; then
            ledger_add "$name" 'failed' \
                "no source path is known for role '$role', so it cannot be staged into the delivery"
            stage_failed=1
            break
        fi
        if [[ ! -f "$path" ]]; then
            ledger_add "$name" 'failed' \
                "'$role' is recorded with bytes but $(shown_path "$path") is not on disk, so the delivery would be missing a file the build claims to have produced"
            stage_failed=1
            break
        fi
        cp "$path" "$delivery/$leaf"
    done < "$roles_list"
    rm -f "$roles_list"
    if (( stage_failed )); then
        return 1
    fi
    if ! run_unipad -m unipad.host.material_manifest --verify \
            --manifest "$manifest" \
            --root "$delivery" \
            --board "$board" \
            --expect-build "$RUN_ID" \
            2>&1 | tee "$delivery/${name}.verify.log"; then
        ledger_add "$name" 'failed' \
            "the material manifest does not verify; see $(shown_path "$delivery/${name}.verify.log"). Nothing in this delivery may be read as a matched build"
        return 1
    fi

    # (4) the measured sizes, in the log, because "is the seed small enough to
    #     travel" is a question about a number and not about a judgement.  The
    #     logical size is 1 GiB (that is what resizeContainer grew the container
    #     to) and the packed size is what actually moves; quoting only one of
    #     the two is how a 1 GiB volume gets mistaken for a 1 GiB download.
    local seed_bytes packed_bytes
    seed_bytes="$(wc -c <"$seed" | tr -d ' ')"
    packed_bytes="$(wc -c <"$delivery/owner-data-1g.dbr" 2>/dev/null | tr -d ' ' || printf '0')"
    log "material: Data seed $seed_bytes bytes packed (logical 1 GiB); the manifest is $(shown_path "$manifest")"

    # (5) the private channel.  Every Apple-derived member of the delivery is
    #     encrypted, not only the seed.  The seed is the OS volume's own
    #     private/var; the donor kernelcache is the original Apple binary
    #     board.toml [kernel.prelink] pins; the trust bundle is the static and
    #     System trust caches the chain lifted out of the same IPSW.  All three
    #     are Apple material under PRD 12, and this repository is PUBLIC, so an
    #     artifact uploaded from it is publicly downloadable -- "controlled
    #     private" is not a property a public repo's artifact has.  Three things
    #     keep the plaintext out, and the third is the one that is meant to
    #     matter: the staging step excludes everything under private/ by
    #     pattern, the plaintext is deleted here the moment it has a ciphertext
    #     so it never coexists with the staging step at all, and what travels is
    #     the ciphertext rather than the bytes.  The delivery stays flat -- each
    #     ciphertext sits beside the manifest that describes it, which is the
    #     same layout the manifest's leaf names assume.
    #
    #     The built artifacts (kernel.macho, kernel.macho.adt, unixnu.toml) are
    #     NOT encrypted: they are this project's own output, and encrypting them
    #     would make a delivery unreadable to anyone checking the build without
    #     the key -- which is the opposite of what a verifiable delivery is for.
    local -a apple_derived=('owner-data-1g.dbr' 'kernelcache.decompressed'
                            'original-static-system.bundle')
    local encrypted_count=0 member ossl encrypt_error keg
    keg="$(openssl_keg)"
    ossl="$(openssl_bin)"
    if [[ -n "$keg" ]]; then
        log "material: encrypting the Apple-derived members with $(shown_path "$ossl") (the OpenSSL 3 keg)"
    else
        log "material: no OpenSSL 3 keg on this host, so encrypting with $(shown_path "$ossl") -- whatever 'openssl' resolves to"
    fi
    if [[ -n "${MATERIAL_DELIVERY_KEY:-}" ]]; then
        for member in "${apple_derived[@]}"; do
            # Not a skip.  Reaching (5) means (3) staged every role the manifest
            # records with bytes, and all three of these are required roles, so a
            # member that is absent here is a member the manifest names and the
            # delivery does not have -- which is the failure the verify in (3)
            # exists to catch, and it cannot catch it if the file is simply not
            # encrypted either.
            if [[ ! -f "$delivery/$member" ]]; then
                ledger_add "$name" 'failed' \
                    "'$member' is an Apple-derived member the manifest records, but $(shown_path "$delivery/$member") is not in the delivery, so it can neither be encrypted nor verified"
                return 1
            fi
            # The cipher is CBC and not GCM, and that is measured rather than
            # preferred.  OpenSSL's ``enc`` command refuses AEAD ciphers
            # outright -- GCM among them -- with ``enc: AEAD ciphers not
            # supported``, on OpenSSL 3 as well as on LibreSSL.  Measured on run
            # 40397080085, which resolved the keg correctly and still failed, and
            # whose message is the only reason this is known: the previous
            # revision's stderr went to a file under private/ that is never
            # uploaded, so the same failure on run 40392771419 left no line at
            # all.  ``-aes-256-gcm`` is what the first revision of this step
            # specified, and it had never been executed even once -- the same
            # shape as the here-document in fact 94 and the leaf search in fact
            # 93.
            if ! encrypt_error="$("$ossl" enc -aes-256-cbc -pbkdf2 -salt \
                    -in "$delivery/$member" \
                    -out "$delivery/$member.enc" \
                    -pass env:MATERIAL_DELIVERY_KEY 2>&1)"; then
                # Logged, not only recorded.  ``ledger_add`` appends to an array
                # and prints nothing, and the openssl stderr used to go to a file
                # under private/ -- which is never uploaded.  Measured on run
                # 40392771419: the encryption failed and the step log carried no
                # line about it at all, so the only way to find out why was to
                # guess.  A refusal the operator cannot read is not a refusal.
                log "material: $member could NOT be encrypted by $(shown_path "$ossl"): ${encrypt_error:-<no output>}"
                ledger_add "$name" 'failed' \
                    "MATERIAL_DELIVERY_KEY was given but $member could not be encrypted by $ossl: ${encrypt_error:-<no output>}"
                return 1
            fi
            # Deleted the moment it has a ciphertext, for the reason the
            # workflow's own removal step gives: an exclusion is a record that a
            # file existed, and the file should not exist at all.  Verification
            # already ran against these exact bytes (step 3), so deleting them
            # costs nothing the manifest has not recorded.
            rm -f "$delivery/$member"
            log "material: $member is encrypted into $(shown_path "$delivery/$member.enc") ($(wc -c <"$delivery/$member.enc" | tr -d ' ') bytes of ciphertext); the plaintext is gone from this runner"
            encrypted_count=$(( encrypted_count + 1 ))
        done
        ledger_add "$name" 'ran' \
            "the material manifest verifies and $encrypted_count Apple-derived members are encrypted into $(shown_path "$delivery"); decrypt with MATERIAL_DELIVERY_KEY (the Data seed is $packed_bytes bytes packed)"
    else
        ledger_add "$name" 'ran' \
            "the material manifest verifies ($packed_bytes bytes packed); MATERIAL_DELIVERY_KEY is unset, so the Apple-derived members were NOT encrypted and no delivery was uploaded -- the workflow's removal step deletes them from this runner and they must never reach the public artifact path (PRD 12)"
        log 'material: MATERIAL_DELIVERY_KEY is unset, so the Apple-derived members stay on this runner unencrypted and nothing is uploaded.'
    fi
    return 0
}

