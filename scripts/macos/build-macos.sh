# read_board_fields -- NAME<TAB>VALUE per line, read from board.toml of the
# device repository with the interpreter the manifest writer already requires.
# board.toml is TOML and its comments mention section names, so a grep would
# match prose; tomllib is the only honest reader.
read_board_fields() {
    "$PY" - "$DEVICE_DIR/board.toml" <<'PY'
import sys
try:
    import tomllib
except ImportError:  # pragma: no cover - the driver itself needs 3.11 (cli.py:204)
    sys.stderr.write('python 3.11 or newer is required to read board.toml (tomllib)\n')
    sys.exit(3)
try:
    with open(sys.argv[1], 'rb') as handle:
        board = tomllib.load(handle)
except FileNotFoundError:
    board = {}
except tomllib.TOMLDecodeError as error:
    sys.stderr.write('board.toml: %s\n' % error)
    sys.exit(1)
fields = (
    ('board_name', board.get('board', {}).get('name', '')),
    ('defconfig', board.get('kernel', {}).get('defconfig', '')),
    ('has_firmware', 'yes' if board.get('firmware') else 'no'),
    ('adt_tool', board.get('payload', {}).get('adt', {}).get('tool', '')),
    # [payload], for build-payload.  loader defaults to "firmware" the way
    # payload.py:173 reads it, because that is the spelling the driver would use
    # if the key were absent -- not because this board says it.
    ('payload_loader', board.get('payload', {}).get('loader', '') or 'firmware'),
    ('payload_volume', board.get('payload', {}).get('volume', '')),
    ('payload_size_mib', board.get('payload', {}).get('size_mib', '')),
    ('payload_dram_size', board.get('payload', {}).get('dram_size', '')),
    ('payload_panic_screen', 'yes' if board.get('payload', {}).get('panic_screen') else 'no'),
    ('payload_skip_setup_tool', board.get('payload', {}).get('skip_setup_tool', '')),
    # Comma-joined, never a tab or a newline: the reader below splits on tab, and
    # a value carrying one would silently truncate the rest of the line.
    ('payload_trust_cache_sha256', ','.join(board.get('payload', {}).get('trust_cache_sha256', []) or [])),
)
for name, value in fields:
    print('%s\t%s' % (name, '' if value is None else value))
PY
}

resolve_board() {
    [[ -n "$PY" ]] || die 'blocked' 'no Python interpreter to read board.toml.' \
        '{}' "$EXIT_BLOCKED"
    local key value
    while IFS="$(printf '\t')" read -r key value; do
        value="${value%$'\r'}"
        case "$key" in
            board_name)    BOARD_NAME="$value" ;;
            defconfig)     DEFCONFIG="$value" ;;
            has_firmware)  BOARD_HAS_FIRMWARE="$value" ;;
            adt_tool)      ADT_TOOL="$value" ;;
            payload_loader)             PAYLOAD_LOADER="$value" ;;
            payload_volume)             PAYLOAD_VOLUME="$value" ;;
            payload_size_mib)           PAYLOAD_SIZE_MIB="$value" ;;
            payload_dram_size)          PAYLOAD_DRAM_SIZE="$value" ;;
            payload_panic_screen)       PAYLOAD_PANIC_SCREEN="$value" ;;
            payload_skip_setup_tool)    PAYLOAD_SKIP_SETUP_TOOL="$value" ;;
            payload_trust_cache_sha256) PAYLOAD_TRUST_CACHE_SHA256="$value" ;;
        esac
    done < <(read_board_fields)
    if [[ -z "$BOARD_NAME" ]]; then
        die 'config_invalid' \
            "board.toml of $DEVICE_DIR has no [board] name; the driver cannot place its output (config.py:76-78)." \
            "{\"device\":\"$(json_escape "$DEVICE_DIR")\"}" "$EXIT_USAGE"
    fi
    log "driver:  $DRIVER"
    log "device:  $DEVICE_DIR (board $BOARD_NAME)"
    log "out:     $UNIXNU_OUT"
}

