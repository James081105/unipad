                           the kernel, the Apple-format device tree this machine
                           boots, and EFI/UniXNU/unixnu.toml naming
                           Payloads/DarwinBoot.efi as a driver.  Opt-in because
                           it needs qemu-system-aarch64 on the runner, which the
                           step installs with brew when it is absent, and because
                           a milestone must not change meaning for a caller that
                           never asked for an ESP.  BUILD_PAYLOAD=1 is the
                           environment spelling; the flag wins over it.
  --dry-run                Validate everything and print the plan; write
                           nothing and run nothing.
  -h, --help               This text.

Notes:
  * No network access of any kind: nothing is fetched, cloned or pulled.  The
    upstream driver fetches on its own when its feeds are missing, so the
    script proves the feeds are already on disk first and refuses otherwise.
  * qemu-system-aarch64 is NOT a preflight requirement and is used by exactly
    two things: build-devicetree/adt and build-payload, both of which need the
    machine's own device tree, which make-qemu-adt.py dumps through it
    (make-qemu-adt.py:93-101).  Both install it with `brew install qemu` when it
    is absent and record not_run when it cannot be had.  The rest of the build
    does not touch it, which is why an absent QEMU never stopped anything else.
  * The build stages are real invocations of the upstream driver.  The Apple
    toolchain the kernel and the bootloader need exists on macOS only, so on any
    other host they record not_run with that reason; see STATUS at the top of
    this file.
  * material-manifest runs last, after every build stage, and binds the run's
    material to one build id: it hashes every artifact, checks each against the
    pins in board.toml, and re-derives the Data volume UUID from the seed's own
    volume superblock so it can be compared to the one the kernel was built
    with.  It verifies the staged delivery, not the tree, and a verification
    failure is a failed stage.  The seed is Apple-derived (PRD 12): with
    MATERIAL_DELIVERY_KEY set every Apple-derived member is encrypted with
    `openssl enc -aes-256-cbc -pbkdf2 -salt` into out/private and the plaintext
    never leaves the runner; without it the step records that the members were
    NOT encrypted and must be collected from the runner directly.  Either way the
    staging step's default-deny keeps them off the public artifact path.  CBC and
    not GCM: `enc` refuses AEAD ciphers on OpenSSL 3 as well as LibreSSL
    (measured, run 40397080085).
EOF
}

