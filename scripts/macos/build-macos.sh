# Prints the planned step names for a milestone, one per line.
plan_steps() {
    local n="$1"
    printf 'preflight\n'
    if (( n >= 1 )); then printf 'prepare-sources\n'; fi
    # build-os-root sits immediately before build-kernel because the kernel stage
    # is what consumes its output: qemu_root_defconfig names two of the archives
    # it builds, and the Data volume UUID it reads from the environment.  Placing
    # it anywhere later would mean the kernel was already built with the wrong
    # config by the time the chain existed.
    if (( n >= 2 )); then printf 'build-os-root\n'; fi
    if (( n >= 2 )); then printf 'build-kernel\n'; fi
    if (( n >= 3 )); then printf 'build-bootloader\n'; fi
    # build-payload sits here, immediately after the bootloader it loads as a
    # driver and before the device tree it would otherwise duplicate.  It is
    # opt-in (--payload / BUILD_PAYLOAD) rather than milestone-gated: the plan
    # below is what every milestone MEANS, and adding a stage to it changes that
    # meaning for every caller that never asked for an ESP.  The runner asks; a
    # caller that does not gets exactly the plan it had before.
    if (( BUILD_PAYLOAD )); then printf 'build-payload\n'; fi
    if (( n >= 4 )); then printf 'build-devicetree\n'; fi
    if (( n >= 9 )); then printf 'assemble-image\n'; fi
    printf 'verify-artifacts\n'
    printf 'write-manifest\n'
    # material-manifest is last because it binds the build's material together
    # and verifies the binding: everything it names must already exist.  It is
    # not milestone-gated for the same reason the plan above is -- adding it to
    # milestone 9 only would mean a --milestone 4 caller silently loses it.
    printf 'material-manifest\n'
}

